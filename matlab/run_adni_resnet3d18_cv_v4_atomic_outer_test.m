function validate_cell_envelope(cellResult,fold,seed,cellRoot)
assert(cellResult.Passed && cellResult.FullValidationCell && ...
    cellResult.Contract.Fold == fold && cellResult.Contract.Seed == seed && ...
    string(cellResult.Contract.OutputRoot) == string(cellRoot) && ...
    cellResult.CompletedStageArtifacts == 5 && ...
    cellResult.TrainingOnlyCalibration && ...
    cellResult.ValidationOnlyEvaluation && ...
    cellResult.AllStageArtifactsReused && ...
    ~cellResult.OuterTestPredictionsComputed && ...
    ~cellResult.OuterTestEvaluated && cellResult.OuterTestSealed, ...
    "NMA:InvalidCVV4AtomicOuterCellEnvelope", ...
    "A frozen fold-seed cell is invalid.");
for index = 1:numel(cellResult.StageArtifactFiles)
    assert(stamp_matches( ...
        file_stamp(cellResult.StageArtifactFiles(index)), ...
        cellResult.StageArtifactStamps(index)), ...
        "NMA:ChangedCVV4AtomicOuterStageArtifact", ...
        "A frozen Phase-2 stage artifact changed.");
end
end

