assert(preflight.Passed && ...
    preflight.Phase4AtomicOuterTestAuthorized && ...
    preflight.CompletedPhase3CellAudits == 25 && ...
    preflight.ExpectedEvaluations == 75 && ...
    preflight.ExpectedPredictionRows == 9585 && ...
    preflight.AtomicBatchRequired && ...
    ~preflight.OuterTestPredictionsComputed && ...
    ~preflight.OuterTestEvaluated && preflight.OuterTestSealed, ...
    "NMA:InvalidCVV4AtomicOuterPreflight", ...
    "The atomic outer-test preflight is invalid.");
validate_metadata(preflight.InputMetadata, ...
    "NMA:ChangedCVV4AtomicOuterPreflightInput");
end

