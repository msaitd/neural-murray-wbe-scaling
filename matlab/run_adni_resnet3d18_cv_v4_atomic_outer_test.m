        source = load(cellResultFiles(cellIndex),"cellResult");
        cellResult = source.cellResult;
        validate_cell_envelope(cellResult,fold,seed,cellRoot);
        for methodIndex = 1:numel(methods)
            evaluationIndex = evaluationIndex+1;
            modelArtifactFiles(evaluationIndex) = ...
                cellResult.StageArtifactFiles( ...
                artifactStageIndices(methodIndex));
        end
        clear source cellResult
    end
end
assert(all(isfile(manifestFiles)) && all(isfile(modelArtifactFiles)), ...
    "NMA:MissingCVV4AtomicOuterInput", ...
    "A frozen manifest or model artifact is missing.");

