function record = make_metric_record( ...
    index,fold,seed,method,artifactFile,artifact,network,metrics,confusion)
spec = nma_resnet3d18_spec(network);
widths = double(spec.BaselineWidths(:));
parameterCount = sum(cellfun(@numel,network.Learnables.Value));
analyticalParameters = nma_resnet3d18_resource( ...
    widths,Resource="parameters",NumClasses=3);
macs = nma_resnet3d18_resource(widths,Resource="macs",NumClasses=3);
activation = nma_resnet3d18_resource( ...
    widths,Resource="activation",NumClasses=3);
denseParameters = nma_resnet3d18_resource( ...
    [64;128;256;512],Resource="parameters",NumClasses=3);
denseMACs = nma_resnet3d18_resource( ...
    [64;128;256;512],Resource="macs",NumClasses=3);
denseActivation = nma_resnet3d18_resource( ...
    [64;128;256;512],Resource="activation",NumClasses=3);
assert(parameterCount == analyticalParameters && ...
    artifact.Passed && ~artifact.OuterTestEvaluated, ...
    "NMA:InvalidCVV4AtomicOuterResourceRecord", ...
    "A frozen model or analytical parameter count is invalid.");
stamp = file_stamp(artifactFile);
record = empty_metric_record();
record.EvaluationIndex = index;
record.Fold = fold;
record.Seed = seed;
record.Method = method;
record.Width1 = widths(1);
record.Width2 = widths(2);
record.Width3 = widths(3);
record.Width4 = widths(4);
record.ParameterCount = parameterCount;
record.ParameterFraction = parameterCount/denseParameters;
record.MACs = macs;
record.MACFraction = macs/denseMACs;
record.ActivationProxy = activation;
record.ActivationFraction = activation/denseActivation;
record.ModelTensorBytes = network_tensor_bytes(network);
record.BestEpoch = artifact.Training.BestEpoch;
record.EpochsRun = height(artifact.Training.History);
record.Accuracy = metrics.Accuracy;
record.BalancedAccuracy = metrics.BalancedAccuracy;
record.MacroF1 = metrics.MacroF1;
record.RecallAD = metrics.RecallAD;
record.RecallCN = metrics.RecallCN;
record.RecallMCI = metrics.RecallMCI;
record.MacroAUROC = metrics.MacroAUROC;
record.NegativeLogLikelihood = metrics.NegativeLogLikelihood;
record.BrierScore = metrics.BrierScore;
record.ECE = metrics.ECE;
record.ConfusionADAD = confusion(1,1);
record.ConfusionADCN = confusion(1,2);
record.ConfusionADMCI = confusion(1,3);
record.ConfusionCNAD = confusion(2,1);
record.ConfusionCNCN = confusion(2,2);
record.ConfusionCNMCI = confusion(2,3);
record.ConfusionMCIAD = confusion(3,1);
record.ConfusionMCICN = confusion(3,2);
record.ConfusionMCIMCI = confusion(3,3);
record.ArtifactFile = string(artifactFile);
record.ArtifactBytes = stamp.Bytes;
record.ArtifactModified = stamp.Modified;
record.OuterTestEvaluated = true;
record.Passed = true;
end

function bytes = network_tensor_bytes(network)
bytes = 0;
values = [network.Learnables.Value;network.State.Value];
for index = 1:numel(values)
    value = values{index};
    if isa(value,"dlarray")
        value = extractdata(value);
    end
    assert(~isa(value,"gpuArray"), ...
        "NMA:UnexpectedCVV4SerializedGPUTensor", ...
        "Frozen model artifacts must contain CPU-resident tensors.");
    information = whos("value");
    bytes = bytes+information.bytes;
end
end

function validate_complete_prediction_grid(predictions,seeds,methods)
assert(all(ismember(predictions.TrueGroup,["AD";"CN";"MCI"])) && ...
    all(ismember(predictions.PredictedGroup,["AD";"CN";"MCI"])) && ...
    all(isfinite(predictions{:,{'ScoreAD','ScoreCN','ScoreMCI'}}),"all"), ...
    "NMA:InvalidCVV4AtomicOuterPrediction", ...
    "The complete outer prediction table has invalid values.");
referenceTruth = unique(predictions(:,["Subject","TrueGroup"]),"rows");
assert(height(referenceTruth) == 639 && ...
    numel(unique(referenceTruth.Subject)) == 639, ...
    "NMA:InconsistentCVV4AtomicOuterTruth", ...
    "Participant truth labels are inconsistent across the release.");
for seedIndex = 1:numel(seeds)
    for methodIndex = 1:numel(methods)
        rows = predictions( ...
            predictions.Seed == seeds(seedIndex) & ...
            predictions.Method == methods(methodIndex),:);
        assert(height(rows) == 639 && ...
            numel(unique(rows.Subject)) == 639 && ...
            height(unique(rows(:,["Subject","Fold"]),"rows")) == 639 && ...
            isequal(sortrows(rows(:,["Subject","TrueGroup"])), ...
            sortrows(referenceTruth)), ...
            "NMA:IncompleteCVV4AtomicOuterSeedMethod", ...
            "A seed-method outer grid is incomplete or inconsistent.");
    end
end
end

