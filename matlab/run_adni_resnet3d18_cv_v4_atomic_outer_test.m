predictionParts = cell(numEvaluations,1);
metricRecords = repmat(empty_metric_record(),numEvaluations,1);
cellIndex = 0;
evaluationIndex = 0;
for foldIndex = 1:numel(folds)
    fold = folds(foldIndex);
    manifestFile = manifestFiles(foldIndex);
    manifest = readtable( ...
        manifestFile,Delimiter=",",TextType="string", ...
        VariableNamingRule="preserve");
    testRows = manifest(manifest.split == "test",:);
    expectedTestSubjects = [129;128;128;127;127];
    assert(height(testRows) == expectedTestSubjects(foldIndex) && ...
        numel(unique(testRows.subject)) == height(testRows) && ...
        all(testRows.visit == "sc") && all(isfile(testRows.matPath)), ...
        "NMA:InvalidCVV4AtomicOuterManifest", ...
        "Fold %d does not satisfy the frozen outer-test contract.",fold);
    for seedIndex = 1:numel(seeds)
        seed = seeds(seedIndex);
        cellIndex = cellIndex+1;
        cellSource = load(cellResultFiles(cellIndex),"cellResult");
        cellResult = cellSource.cellResult;
        validate_cell_envelope( ...
            cellResult,fold,seed,fileparts(cellResultFiles(cellIndex)));
        for methodIndex = 1:numel(methods)
            evaluationIndex = evaluationIndex+1;
            method = methods(methodIndex);
            artifactFile = modelArtifactFiles(evaluationIndex);
            assert(stamp_matches( ...
                file_stamp(artifactFile), ...
                cellResult.StageArtifactStamps( ...
                artifactStageIndices(methodIndex))), ...
                "NMA:ChangedCVV4AtomicOuterModel", ...
                "A frozen model changed before outer evaluation.");
            artifactPayload = load( ...
                artifactFile,artifactVariables(methodIndex));
            artifact = artifactPayload.(artifactVariables(methodIndex));
            network = artifact.Training.Network;
            evaluation = adni_evaluate_resnet3d18( ...
                network,manifestFile,Split="test", ...
                ExecutionEnvironment="gpu",BootstrapReplicates=0);
            scores = evaluation.SubjectPredictions{:, ...
                {'ScoreAD','ScoreCN','ScoreMCI'}};
            [metrics,confusion,predictedGroup] = ...
                adni_resnet3d18_cv_v4_metrics( ...
                evaluation.SubjectPredictions.TrueGroup,scores);
            assert(evaluation.Split == "test" && ...
                evaluation.NumSubjects == height(testRows) && ...
                isequal(predictedGroup, ...
                evaluation.SubjectPredictions.PredictedGroup) && ...
                abs(metrics.Accuracy-evaluation.Accuracy) <= 1e-12 && ...
                abs(metrics.BalancedAccuracy- ...
                evaluation.BalancedAccuracy) <= 1e-12 && ...
                abs(metrics.MacroF1-evaluation.MacroF1) <= 1e-12 && ...
                isequal(confusion,evaluation.ConfusionMatrix), ...
                "NMA:InvalidCVV4AtomicOuterEvaluation", ...
                "An outer-test evaluation failed metric self-validation.");
            predictions = evaluation.SubjectPredictions;
            predictions = addvars( ...
                predictions,repmat(fold,height(predictions),1), ...
                repmat(seed,height(predictions),1), ...
                repmat(method,height(predictions),1), ...
                'Before',1,'NewVariableNames',["Fold","Seed","Method"]);
            predictionParts{evaluationIndex} = predictions;
            metricRecords(evaluationIndex) = make_metric_record( ...
                evaluationIndex,fold,seed,method,artifactFile, ...
                artifact,network,metrics,confusion);
            fprintf( ...
                "CV_V4_ATOMIC_OUTER_PROGRESS evaluation %d/%d fold %d seed %d method %s\n", ...
                evaluationIndex,numEvaluations,fold,seed,method);
            clear artifactPayload artifact network evaluation scores
            clear metrics confusion predictedGroup predictions
        end
        clear cellSource cellResult
    end
end

