%% Audit one locked v4 validation cell in a fresh MATLAB process.
addpath(fileparts(mfilename("fullpath")));
parallel.gpu.enableCUDAForwardCompatibility(true);

fold = str2double(getenv("ADNI_V4_CELL_FOLD"));
seed = str2double(getenv("ADNI_V4_CELL_SEED"));
assert(isscalar(fold) && isfinite(fold) && ...
    fold == round(fold) && ismember(fold,1:5), ...
    "NMA:InvalidCVV4AuditCellFold", ...
    "ADNI_V4_CELL_FOLD must be an integer from 1 through 5.");
assert(isscalar(seed) && isfinite(seed) && ...
    seed == round(seed) && ismember(seed,20260820:20260824), ...
    "NMA:InvalidCVV4AuditCellSeed", ...
    "ADNI_V4_CELL_SEED is not a locked v4 seed.");

audit = adni_audit_resnet3d18_cv_v4_validation_cell_recovery( ...
    fold,seed,Verbose=true);
assert(audit.Passed && audit.OuterTestSealed && ...
    ~audit.OuterTestPredictionsComputed && ...
    ~audit.OuterTestEvaluated, ...
    "NMA:InvalidCVV4AuditCellResult", ...
    "The v4 cell auditor returned an invalid result.");
fprintf( ...
    "ADNI_RESNET3D18_CV_V4_AUDIT_CELL_STAGE_PASS fold %d seed %d\n", ...
    fold,seed);
