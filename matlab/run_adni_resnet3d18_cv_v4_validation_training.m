%% Aggregate the completed 5-fold x 5-seed v4 validation-only training.
addpath(fileparts(mfilename("fullpath")));
parallel.gpu.enableCUDAForwardCompatibility(true);

scriptDirectory = fileparts(mfilename("fullpath"));
projectRoot = fileparts(scriptDirectory);
workRoot = fullfile(projectRoot,"adni_work");
preflightFile = fullfile( ...
    workRoot,"adni_3d_cv_v4","full_validation_preflight", ...
    "v4_full_validation_preflight.mat");
assert(isfile(preflightFile), ...
    "NMA:MissingCVV4FullValidationPreflight", ...
    "Run the full v4 validation preflight before Phase 2.");
preflightSource = load(preflightFile,"preflight");
preflight = preflightSource.preflight;
validate_preflight(preflight);
preflightStamp = file_stamp(preflightFile);

folds = (1:5).';
seeds = (20260820:20260824).';
numCells = numel(folds)*numel(seeds);
outputRoot = fullfile( ...
    workRoot,"adni_3d_cv_v4", ...
    "locked_internal_validation_training");
if ~isfolder(outputRoot)
    mkdir(outputRoot);
end
progressFile = fullfile(outputRoot,"v4_validation_training_progress.mat");
resultFile = fullfile(outputRoot,"v4_validation_training_result.mat");

records = repmat(empty_cell_record(),numCells,1);
summaryParts = cell(numCells,1);
cellIndex = 0;
for foldIndex = 1:numel(folds)
    fold = folds(foldIndex);
    for seedIndex = 1:numel(seeds)
        seed = seeds(seedIndex);
        cellIndex = cellIndex+1;
        cellRoot = fullfile( ...
            outputRoot,"fold_"+fold,"seed_"+seed);
        cellResultFile = fullfile(cellRoot,"validation_cell_result.mat");
        assert(isfile(cellResultFile), ...
            "NMA:MissingCompletedCVV4ValidationCell", ...
            ["The fresh-session cell stages must complete before " ...
            "aggregation: fold %d seed %d."],fold,seed);
        source = load(cellResultFile,"cellResult");
        cellResult = source.cellResult;
        validate_completed_cell( ...
            cellResult,fold,seed,cellRoot,preflightStamp);
        fprintf( ...
            "Loaded completed full v4 cell fold %d seed %d.\n", ...
            fold,seed);
        records(cellIndex) = make_cell_record( ...
            cellIndex,cellResultFile,cellResult);
        cellSummary = cellResult.ValidationSummary;
        cellSummary = addvars( ...
            cellSummary,repmat(fold,height(cellSummary),1), ...
            repmat(seed,height(cellSummary),1), ...
            'Before',1,'NewVariableNames',["Fold","Seed"]);
        summaryParts{cellIndex} = cellSummary;

        progress = struct;
        progress.Design = ...
            "v4 full validation-only training progress";
        progress.PreflightStamp = preflightStamp;
        progress.Folds = folds;
        progress.Seeds = seeds;
        progress.ExecutionOrder = "fold-major-then-seed-major";
        progress.Records = records;
        progress.CompletedCells = cellIndex;
        progress.TotalCells = numCells;
        progress.CompletedDenseTeachers = cellIndex;
        progress.CompletedCompressedStudents = 2*cellIndex;
        progress.OuterTestPredictionsComputed = false;
        progress.OuterTestEvaluated = false;
        progress.OuterTestSealed = true;
        progress.UpdatedAt = datetime("now",TimeZone="local");
        atomic_save(progressFile,"progress",progress);
        fprintf( ...
            "CV_V4_FULL_PROGRESS cell %d/%d fold %d seed %d NMA [%s]\n", ...
            cellIndex,numCells,fold,seed, ...
            strjoin(string([ ...
            records(cellIndex).NMAWidth1, ...
            records(cellIndex).NMAWidth2, ...
            records(cellIndex).NMAWidth3, ...
            records(cellIndex).NMAWidth4])," "));
        clear source cellResult cellSummary progress
    end
end

perCellMethodSummary = vertcat(summaryParts{:});
assert(height(perCellMethodSummary) == 75 && ...
    sum(perCellMethodSummary.Method == "dense") == 25 && ...
    sum(perCellMethodSummary.Method == "proportional") == 25 && ...
    sum(perCellMethodSummary.Method == "multi-resource-NMA") == 25 && ...
    all(isfinite(perCellMethodSummary{:,8:end}),"all"), ...
    "NMA:IncompleteCVV4FullValidationSummary", ...
    "The 75-row full v4 validation summary is incomplete.");

run = struct;
run.Design = ...
    "locked 5-fold x 5-seed pretrained-teacher validation-only training";
run.ProtocolFile = fullfile( ...
    projectRoot,"ADNI_NMA_CV_V4_LOCKED_INTERNAL_VALIDATION_PROTOCOL.md");
run.PreflightFile = preflightFile;
run.PreflightStamp = preflightStamp;
run.Folds = folds;
run.Seeds = seeds;
run.ExecutionOrder = "fold-major-then-seed-major";
run.Methods = ["dense";"proportional";"multi-resource-NMA"];
run.Records = records;
run.PerCellMethodSummary = perCellMethodSummary;
run.CompletedCells = numCells;
run.CompletedDenseTeachers = numCells;
run.CompletedCompressedStudents = 2*numCells;
run.TotalNetworks = 3*numCells;
run.ReadyForIndependentPreTestAudit = true;
run.PredictiveMetricsForInference = false;
run.OuterTestPredictionsComputed = false;
run.OuterTestEvaluated = false;
run.OuterTestSealed = true;
run.Passed = true;
run.CompletedAt = datetime("now",TimeZone="local");
atomic_save(resultFile,"run",run);
writetable(struct2table(records),fullfile( ...
    outputRoot,"v4_validation_training_cells.csv"),Encoding="UTF-8");
writetable(perCellMethodSummary,fullfile( ...
    outputRoot,"v4_validation_training_per_cell_method.csv"), ...
    Encoding="UTF-8");

disp(struct2table(records));
fprintf( ...
    "CV_V4_FULL_VALIDATION_TRAINING cells %d teachers %d students %d testSealed %d\n", ...
    run.CompletedCells,run.CompletedDenseTeachers, ...
    run.CompletedCompressedStudents,run.OuterTestSealed);
fprintf( ...
    "ADNI_RESNET3D18_CV_V4_FULL_VALIDATION_TRAINING_PASS\n");

function record = empty_cell_record()
record = struct( ...
    "CellIndex",NaN,"Fold",NaN,"Seed",NaN, ...
    "ResultFile","","ResultFileBytes",NaN, ...
    "ResultFileModified",NaN, ...
    "DenseBestEpoch",NaN,"ProportionalBestEpoch",NaN, ...
    "NMABestEpoch",NaN,"NMAWidth1",NaN,"NMAWidth2",NaN, ...
    "NMAWidth3",NaN,"NMAWidth4",NaN, ...
    "NMAParameters",NaN,"NMAMACs",NaN, ...
    "OuterTestEvaluated",false,"Passed",false);
end

function record = make_cell_record(index,resultFile,cellResult)
information = dir(resultFile);
assert(isscalar(information), ...
    "NMA:MissingCVV4CellResultAfterRun", ...
    "A full v4 cell did not save its result.");
denseRow = cellResult.ValidationSummary( ...
    cellResult.ValidationSummary.Method == "dense",:);
proportionalRow = cellResult.ValidationSummary( ...
    cellResult.ValidationSummary.Method == "proportional",:);
nmaRow = cellResult.ValidationSummary( ...
    cellResult.ValidationSummary.Method == "multi-resource-NMA",:);
denseSource = load( ...
    cellResult.StageArtifactFiles(2),"denseArtifact");
proportionalSource = load( ...
    cellResult.StageArtifactFiles(4),"proportionalArtifact");
nmaSource = load( ...
    cellResult.StageArtifactFiles(5),"nmaArtifact");
record = empty_cell_record();
record.CellIndex = index;
record.Fold = cellResult.Contract.Fold;
record.Seed = cellResult.Contract.Seed;
record.ResultFile = resultFile;
record.ResultFileBytes = information.bytes;
record.ResultFileModified = information.datenum;
record.DenseBestEpoch = denseSource.denseArtifact.Training.BestEpoch;
record.ProportionalBestEpoch = ...
    proportionalSource.proportionalArtifact.Training.BestEpoch;
record.NMABestEpoch = nmaSource.nmaArtifact.Training.BestEpoch;
record.NMAWidth1 = nmaRow.Width1;
record.NMAWidth2 = nmaRow.Width2;
record.NMAWidth3 = nmaRow.Width3;
record.NMAWidth4 = nmaRow.Width4;
record.NMAParameters = nmaRow.ParameterCount;
record.NMAMACs = nmaRow.MACs;
record.OuterTestEvaluated = false;
record.Passed = height(denseRow) == 1 && ...
    height(proportionalRow) == 1 && height(nmaRow) == 1;
assert(record.Passed,"NMA:InvalidCVV4CellRecord", ...
    "A full v4 cell summary lacks one of the three methods.");
end

function validate_completed_cell( ...
    cellResult,fold,seed,cellRoot,preflightStamp)
assert(cellResult.Passed && cellResult.FullValidationCell && ...
    cellResult.Contract.Mode == "full-validation" && ...
    cellResult.Contract.Fold == fold && ...
    cellResult.Contract.Seed == seed && ...
    string(cellResult.Contract.OutputRoot) == string(cellRoot) && ...
    stamp_matches( ...
    cellResult.Contract.FullValidationPreflightStamp,preflightStamp) && ...
    cellResult.CompletedStageArtifacts == 5 && ...
    cellResult.TrainingOnlyCalibration && ...
    cellResult.ValidationOnlyEvaluation && ...
    ~cellResult.PredictiveMetricsForInference && ...
    ~cellResult.OuterTestPredictionsComputed && ...
    ~cellResult.OuterTestEvaluated && ...
    cellResult.OuterTestSealed && ...
    height(cellResult.ValidationSummary) == 3 && ...
    height(cellResult.CalibrationRows) == ...
    cellResult.SplitContract.NumTrainRows, ...
    "NMA:InvalidCompletedCVV4Cell", ...
    "Full v4 fold %d seed %d is stale or incomplete.",fold,seed);
for index = 1:numel(cellResult.StageArtifactFiles)
    current = file_stamp(cellResult.StageArtifactFiles(index));
    assert(stamp_matches( ...
        current,cellResult.StageArtifactStamps(index)), ...
        "NMA:ChangedCVV4StageArtifact", ...
        "A full v4 stage artifact changed after cell completion.");
end
end

function validate_preflight(preflight)
assert(preflight.Passed && ...
    preflight.Phase2ValidationTrainingAuthorized && ...
    preflight.SmokeValidationPassed && ...
    preflight.NumCells == 25 && ...
    preflight.OuterTestSealed && ...
    ~preflight.TrainingPerformed && ...
    ~preflight.OuterTestPredictionsComputed && ...
    ~preflight.OuterTestEvaluated, ...
    "NMA:InvalidCVV4FullRunnerPreflight", ...
    "The full v4 runner lacks sealed Phase-2 authorization.");
for index = 1:height(preflight.InputMetadata)
    information = dir(preflight.InputMetadata.Path(index));
    assert(isscalar(information) && ...
        information.bytes == preflight.InputMetadata.Bytes(index) && ...
        information.datenum == preflight.InputMetadata.Modified(index), ...
        "NMA:ChangedCVV4FullRunnerInput", ...
        "A full v4 runner input changed: %s", ...
        preflight.InputMetadata.Path(index));
end
end

function stamp = file_stamp(path)
information = dir(path);
assert(isscalar(information), ...
    "NMA:CVV4FullRunnerStampFailure", ...
    "Could not inspect full v4 file %s.",path);
stamp = struct( ...
    "Path",string(path),"Bytes",information.bytes, ...
    "Modified",information.datenum);
end

function matches = stamp_matches(first,second)
matches = first.Path == second.Path && ...
    first.Bytes == second.Bytes && ...
    first.Modified == second.Modified;
end

function atomic_save(path,variableName,value)
partialFile = path+".partial";
payload = struct;
payload.(variableName) = value;
save(partialFile,"-struct","payload","-v7.3");
movefile(partialFile,path,"f");
end
