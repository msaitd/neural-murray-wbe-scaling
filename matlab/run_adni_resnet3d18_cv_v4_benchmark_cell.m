function values = percentile_columns(data,percentages)
data = sort(data,1);
positions = 1+(size(data,1)-1)*(percentages(:)/100);
values = zeros(numel(percentages),size(data,2));
for index = 1:numel(percentages)
    lowerIndex = floor(positions(index));
    upperIndex = ceil(positions(index));
    weight = positions(index)-lowerIndex;
    values(index,:) = ...
        (1-weight)*data(lowerIndex,:)+weight*data(upperIndex,:);
end
if isscalar(percentages)
    values = values(1,:);
end
end

function metadata = collect_file_metadata(names,paths)
bytes = zeros(numel(paths),1);
modified = zeros(numel(paths),1);
for index = 1:numel(paths)
    information = dir(paths(index));
    assert(isscalar(information), ...
        "NMA:CVV4BenchmarkMetadataFailure", ...
        "Could not inspect a paired-benchmark input.");
    bytes(index) = information.bytes;
    modified(index) = information.datenum;
end
metadata = table( ...
    names,paths,bytes,modified, ...
    VariableNames=["Name","Path","Bytes","Modified"]);
end

function validate_metadata(metadata,errorIdentifier)
for index = 1:height(metadata)
    information = dir(metadata.Path(index));
    assert(isscalar(information) && ...
        information.bytes == metadata.Bytes(index) && ...
        information.datenum == metadata.Modified(index), ...
        errorIdentifier, ...
        "A paired-benchmark input changed: %s",metadata.Path(index));
end
end

function stamp = file_stamp(path)
information = dir(path);
assert(isscalar(information),"NMA:CVV4BenchmarkStampFailure", ...
    "Could not inspect paired-benchmark file %s.",path);
stamp = struct( ...
    "Path",string(path),"Bytes",information.bytes, ...
    "Modified",information.datenum);
end

function matches = stamp_matches(first,second)
matches = first.Path == second.Path && ...
    first.Bytes == second.Bytes && first.Modified == second.Modified;
end

function network = load_frozen_network(path,variableName)
payload = load(path,variableName);
assert(isfield(payload,variableName), ...
    "NMA:MissingCVV4BenchmarkNetworkArtifact", ...
    "A frozen benchmark artifact lacks its expected variable.");
artifact = payload.(variableName);
assert(artifact.Passed && isfield(artifact,"Training") && ...
    isa(artifact.Training.Network,"dlnetwork"), ...
    "NMA:InvalidCVV4BenchmarkNetworkArtifact", ...
    "A frozen benchmark artifact is invalid.");
network = artifact.Training.Network;
end

function atomic_save(path,variableName,value)
partialFile = path+".partial";
payload = struct;
payload.(variableName) = value;
save(partialFile,"-struct","payload","-v7.3");
movefile(partialFile,path,"f");
end

function atomic_writetable(value,path)
partialFile = path+".partial.csv";
writetable(value,partialFile,FileType="text",Delimiter=",", ...
    Encoding="UTF-8");
movefile(partialFile,path,"f");
end
