function distillation = ...
    adni_train_resnet3d18_distillation( ...
    datasetRoot,studentNet,teacherNet,options)
%ADNI_TRAIN_RESNET3D18_DISTILLATION Fine-tune a 3-D student with KD.
%
% The custom loss is
%   alpha * weighted CE(hard labels)
%   + (1-alpha) * temperature^2 * CE(teacher soft labels).
% Teacher and student receive the same augmented 3-D volume. Validation
% balanced accuracy, with macro-F1 as a tie breaker, selects the best epoch.
% The test split is never evaluated in this function.

arguments
    datasetRoot (1,1) string
    studentNet (1,1) dlnetwork
    teacherNet (1,1) dlnetwork
    options.MaxEpochs (1,1) double ...
        {mustBeInteger,mustBePositive} = 3
    options.InitialLearnRate (1,1) double {mustBePositive} = 2e-5
    options.MinimumLearnRateRatio (1,1) double ...
        {mustBeGreaterThanOrEqual(options.MinimumLearnRateRatio,0), ...
        mustBeLessThanOrEqual(options.MinimumLearnRateRatio,1)} = 0
    options.Alpha (1,1) double ...
        {mustBeGreaterThanOrEqual(options.Alpha,0), ...
        mustBeLessThanOrEqual(options.Alpha,1)} = 0.5
    options.Temperature (1,1) double {mustBePositive} = 4
    options.L2Regularization (1,1) double {mustBeNonnegative} = 1e-4
    options.GradientThreshold (1,1) double {mustBePositive} = 5
    options.GradientAccumulationSteps (1,1) double ...
        {mustBeInteger,mustBePositive} = 1
    options.ValidationPatience (1,1) double ...
        {mustBeInteger,mustBePositive} = 3
    options.UseAugmentation (1,1) logical = true
    options.TrainingSampling (1,1) string = "all-visits"
    options.RandomSeed (1,1) double {mustBeInteger} = 20260727
    options.EnableCUDAForwardCompatibility (1,1) logical = true
    options.DeterministicGPU (1,1) logical = true
    options.BatchNormalizationMode (1,1) string ...
        {mustBeMember(options.BatchNormalizationMode, ...
        ["update","frozen"])} = "update"
    options.SaveFile (1,1) string = ""
    options.Verbose (1,1) logical = true
end

if options.EnableCUDAForwardCompatibility
    parallel.gpu.enableCUDAForwardCompatibility(true);
end
assert(canUseGPU,"NMA:GPUUnavailable", ...
    "Knowledge distillation requires the configured GPU.");
if options.DeterministicGPU
    previousDeterminism = ...
        deep.gpu.deterministicAlgorithms(true);
    previousGPUGenerator = gpurng;
    determinismCleanup = onCleanup(@() restore_gpu_state( ...
        previousDeterminism,previousGPUGenerator));
    gpurng(options.RandomSeed,"Threefry");
end
assert(getLayer(studentNet,"fc").OutputSize == ...
    getLayer(teacherNet,"fc").OutputSize, ...
    "NMA:DistillationClassMismatch", ...
    "Teacher and student output sizes must match.");
studentSpec = nma_resnet3d18_spec(studentNet);
teacherSpec = nma_resnet3d18_spec(teacherNet);
initialStudentState = studentNet.State;
initialStudentLearnables = studentNet.Learnables;
assert(isequal(studentSpec.InputSize,teacherSpec.InputSize), ...
    "NMA:DistillationInputMismatch", ...
    "Teacher and student input sizes must match.");

manifestPath = fullfile(datasetRoot,"adni_3d_manifest.csv");
manifest = readtable( ...
    manifestPath,Delimiter=",",TextType="string", ...
    VariableNamingRule="preserve");
trainRows = manifest(manifest.split == "train",:);
validationRows = manifest(manifest.split == "validation",:);
assert(height(trainRows) > 0 && height(validationRows) > 0, ...
    "NMA:IncompleteDistillationSplit", ...
    "Distillation requires nonempty train and validation splits.");
assert(all(isfile(trainRows.matPath)) && ...
    all(isfile(validationRows.matPath)), ...
    "NMA:MissingDistillationVolume", ...
    "A train or validation volume is missing.");
assert(isempty(intersect( ...
    unique(trainRows.subject),unique(validationRows.subject))), ...
    "NMA:DistillationParticipantLeakage", ...
    "Train and validation participants overlap.");

trainingSampling = lower(options.TrainingSampling);
assert(ismember(trainingSampling, ...
    ["all-visits","one-visit-per-subject"]), ...
    "NMA:UnknownDistillationSampling", ...
    "TrainingSampling must be all-visits or one-visit-per-subject.");
trainSubjects = unique(trainRows.subject,"stable");
subjectRowIndices = cell(numel(trainSubjects),1);
subjectGroups = strings(numel(trainSubjects),1);
for subjectIndex = 1:numel(trainSubjects)
    subjectRowIndices{subjectIndex} = find( ...
        trainRows.subject == trainSubjects(subjectIndex));
    groups = unique(trainRows.group( ...
        subjectRowIndices{subjectIndex}));
    assert(isscalar(groups), ...
        "NMA:DistillationSubjectLabelChange", ...
        "A training participant changes class across visits.");
    subjectGroups(subjectIndex) = groups;
end

classNames = ["AD";"CN";"MCI"];
numClasses = numel(classNames);
classCounts = zeros(numClasses,1);
for classIndex = 1:numClasses
    if trainingSampling == "one-visit-per-subject"
        classCounts(classIndex) = ...
            sum(subjectGroups == classNames(classIndex));
    else
        classCounts(classIndex) = ...
            sum(trainRows.group == classNames(classIndex));
    end
end
assert(all(classCounts > 0),"NMA:MissingDistillationClass", ...
    "Every class must occur in the distillation training set.");
classWeights = sum(classCounts)./(numClasses*classCounts);
classWeights = classWeights/mean(classWeights);
classWeightsGPU = gpuArray(single(classWeights(:).'));

initialValidation = adni_evaluate_resnet3d18( ...
    studentNet,manifestPath, ...
    Split="validation",ExecutionEnvironment="gpu", ...
    BootstrapReplicates=0);
bestNet = studentNet;
bestValidation = initialValidation;
bestEpoch = 0;
epochsWithoutImprovement = 0;
trailingAverage = [];
trailingAverageSquared = [];
iteration = 0;
microBatchCount = 0;
frozenGradientTensorsPerUpdate = [];
maximumOptimizerUpdates = options.MaxEpochs*ceil( ...
    max(height(trainRows),numel(trainSubjects))/ ...
    options.GradientAccumulationSteps);
updateEpoch = zeros(maximumOptimizerUpdates,1);
updateEndPosition = zeros(maximumOptimizerUpdates,1);
updateAccumulationCount = zeros(maximumOptimizerUpdates,1);
updateGradientNorm = zeros(maximumOptimizerUpdates,1);
updateWasClipped = false(maximumOptimizerUpdates,1);
updateLearnRate = zeros(maximumOptimizerUpdates,1);
history = table( ...
    zeros(options.MaxEpochs,1), ...
    zeros(options.MaxEpochs,1), ...
    zeros(options.MaxEpochs,1), ...
    zeros(options.MaxEpochs,1), ...
    zeros(options.MaxEpochs,1), ...
    zeros(options.MaxEpochs,1), ...
    false(options.MaxEpochs,1), ...
    VariableNames=[ ...
    "Epoch","LearnRate","TrainingLoss", ...
    "ValidationBalancedAccuracy","ValidationMacroF1", ...
    "ValidationAccuracy","Selected"]);

rng(options.RandomSeed,"twister");
completedEpochs = 0;
for epoch = 1:options.MaxEpochs
    if options.MaxEpochs == 1
        learnRate = options.InitialLearnRate;
    else
        minimumLearnRate = options.InitialLearnRate* ...
            options.MinimumLearnRateRatio;
        learnRate = minimumLearnRate+ ...
            (options.InitialLearnRate-minimumLearnRate)* ...
            0.5*(1+cos(pi*(epoch-1)/(options.MaxEpochs-1)));
    end
    if trainingSampling == "one-visit-per-subject"
        order = zeros(numel(trainSubjects),1);
        for subjectIndex = 1:numel(trainSubjects)
            choices = subjectRowIndices{subjectIndex};
            order(subjectIndex) = ...
                choices(randi(numel(choices)));
        end
        order = order(randperm(numel(order)));
    else
        order = randperm(height(trainRows));
    end
    numEpochSamples = numel(order);
    epochLoss = 0;
    gradientAccumulator = [];
    accumulationCount = 0;
    accumulatedDisplayLoss = 0;
    accumulatedHardLoss = 0;
    accumulatedSoftLoss = 0;
    optimizerUpdatesThisEpoch = 0;
    for position = 1:numel(order)
        row = trainRows(order(position),:);
        if options.UseAugmentation
            volume = adni_read_3d_augmented(row.matPath);
        else
            volume = adni_read_3d_mat(row.matPath);
        end
        X = gpuArray(single(volume));
        T = zeros(numClasses,1,"single","gpuArray");
        T(row.classIndex) = 1;
        dlX = dlarray(X,"SSSCB");
        dlT = dlarray(T,"CB");
        [loss,hardLoss,softLoss,gradients,state] = dlfeval( ...
            @knowledge_distillation_gradients, ...
            studentNet,teacherNet,dlX,dlT,classWeightsGPU, ...
            options.Alpha,options.Temperature, ...
            options.BatchNormalizationMode);
        if options.BatchNormalizationMode == "update"
            studentNet.State = state;
        end
        lossValue = cpu_scalar(loss);
        hardLossValue = cpu_scalar(hardLoss);
        softLossValue = cpu_scalar(softLoss);
        epochLoss = epochLoss+lossValue;
        microBatchCount = microBatchCount+1;
        gradientAccumulator = accumulate_gradients( ...
            gradientAccumulator,gradients);
        accumulationCount = accumulationCount+1;
        accumulatedDisplayLoss = ...
            accumulatedDisplayLoss+lossValue;
        accumulatedHardLoss = ...
            accumulatedHardLoss+hardLossValue;
        accumulatedSoftLoss = ...
            accumulatedSoftLoss+softLossValue;
        updateBoundary = ...
            accumulationCount == ...
            options.GradientAccumulationSteps || ...
            position == numEpochSamples;
        if updateBoundary
            gradients = scale_gradients( ...
                gradientAccumulator,1/accumulationCount);
            gradients = add_l2_gradients( ...
                studentNet,gradients, ...
                options.L2Regularization);
            [gradients,numFrozenGradientTensors] = ...
                mask_frozen_gradients(studentNet,gradients);
            if isempty(frozenGradientTensorsPerUpdate)
                frozenGradientTensorsPerUpdate = ...
                    numFrozenGradientTensors;
            else
                assert( ...
                    frozenGradientTensorsPerUpdate == ...
                    numFrozenGradientTensors, ...
                    "NMA:DistillationFrozenGradientCountChanged", ...
                    "The frozen-gradient tensor count changed.");
            end
            [gradients,gradientNorm] = clip_gradients( ...
                gradients,options.GradientThreshold);
            iteration = iteration+1;
            optimizerUpdatesThisEpoch = ...
                optimizerUpdatesThisEpoch+1;
            updateEpoch(iteration) = epoch;
            updateEndPosition(iteration) = position;
            updateAccumulationCount(iteration) = ...
                accumulationCount;
            updateGradientNorm(iteration) = gradientNorm;
            updateWasClipped(iteration) = ...
                gradientNorm > options.GradientThreshold;
            updateLearnRate(iteration) = learnRate;
            [studentNet,trailingAverage, ...
                trailingAverageSquared] = adamupdate( ...
                studentNet,gradients,trailingAverage, ...
                trailingAverageSquared,iteration,learnRate);
            if options.Verbose && ...
                    (optimizerUpdatesThisEpoch == 1 || ...
                    mod(position,50) == 0 || ...
                    position == numEpochSamples)
                fprintf( ...
                    "KD epoch %d/%d sample %d/%d update %d, "+ ...
                    "loss %.6g hard %.6g soft %.6g "+ ...
                    "trainable-grad %.6g lr %.6g accumulation %d\n", ...
                    epoch,options.MaxEpochs,position, ...
                    numEpochSamples,iteration, ...
                    accumulatedDisplayLoss/accumulationCount, ...
                    accumulatedHardLoss/accumulationCount, ...
                    accumulatedSoftLoss/accumulationCount, ...
                    gradientNorm,learnRate,accumulationCount);
            end
            gradientAccumulator = [];
            accumulationCount = 0;
            accumulatedDisplayLoss = 0;
            accumulatedHardLoss = 0;
            accumulatedSoftLoss = 0;
        end
    end
    assert(accumulationCount == 0 && ...
        optimizerUpdatesThisEpoch == ceil( ...
        numEpochSamples/options.GradientAccumulationSteps), ...
        "NMA:DistillationGradientAccumulationMismatch", ...
        "The number of optimizer updates is invalid.");

    validation = adni_evaluate_resnet3d18( ...
        studentNet,manifestPath, ...
        Split="validation",ExecutionEnvironment="gpu", ...
        BootstrapReplicates=0);
    improved = ...
        validation.BalancedAccuracy > ...
        bestValidation.BalancedAccuracy+1e-12 || ...
        (abs(validation.BalancedAccuracy- ...
        bestValidation.BalancedAccuracy) <= 1e-12 && ...
        validation.MacroF1 > bestValidation.MacroF1+1e-12);
    if improved
        bestNet = studentNet;
        bestValidation = validation;
        bestEpoch = epoch;
        epochsWithoutImprovement = 0;
    else
        epochsWithoutImprovement = epochsWithoutImprovement+1;
    end
    history.Epoch(epoch) = epoch;
    history.LearnRate(epoch) = learnRate;
    history.TrainingLoss(epoch) = epochLoss/numEpochSamples;
    history.ValidationBalancedAccuracy(epoch) = ...
        validation.BalancedAccuracy;
    history.ValidationMacroF1(epoch) = validation.MacroF1;
    history.ValidationAccuracy(epoch) = validation.Accuracy;
    history.Selected(epoch) = improved;
    completedEpochs = epoch;
    if options.Verbose
        fprintf( ...
            "KD validation epoch %d: BA %.6f, macro-F1 %.6f, "+ ...
            "accuracy %.6f, selected %d\n", ...
            epoch,validation.BalancedAccuracy, ...
            validation.MacroF1,validation.Accuracy,improved);
    end
    if epochsWithoutImprovement >= options.ValidationPatience
        break
    end
end
history = history(1:completedEpochs,:);
if options.BatchNormalizationMode == "frozen"
    assert(state_tables_equal( ...
        studentNet.State,initialStudentState) && ...
        state_tables_equal(bestNet.State,initialStudentState), ...
        "NMA:DistillationFrozenStateChanged", ...
        "Frozen BatchNorm state changed during training.");
end
assert_frozen_learnables_equal( ...
    initialStudentLearnables,studentNet);
assert_frozen_learnables_equal( ...
    initialStudentLearnables,bestNet);
optimizerDiagnostics = table( ...
    (1:iteration).',updateEpoch(1:iteration), ...
    updateEndPosition(1:iteration), ...
    updateAccumulationCount(1:iteration), ...
    updateGradientNorm(1:iteration), ...
    updateWasClipped(1:iteration), ...
    updateLearnRate(1:iteration), ...
    VariableNames=[ ...
    "OptimizerUpdate","Epoch","EndSamplePosition", ...
    "AccumulatedMicroBatches","TrainableGradientNorm", ...
    "Clipped","LearnRate"]);

distillation = struct;
distillation.Network = bestNet;
distillation.TeacherWidths = teacherSpec.BaselineWidths;
distillation.StudentWidths = studentSpec.BaselineWidths;
distillation.InitialValidation = initialValidation;
distillation.BestValidation = bestValidation;
distillation.BestEpoch = bestEpoch;
distillation.History = history;
distillation.ClassNames = classNames;
distillation.ClassCounts = classCounts;
distillation.ClassWeights = classWeights;
distillation.Options = options;
distillation.NumTrainRows = height(trainRows);
distillation.NumValidationRows = height(validationRows);
distillation.NumTrainSubjects = ...
    numel(unique(trainRows.subject));
distillation.NumValidationSubjects = ...
    numel(unique(validationRows.subject));
if trainingSampling == "one-visit-per-subject"
    distillation.NumOptimizationSamplesPerEpoch = ...
        numel(trainSubjects);
else
    distillation.NumOptimizationSamplesPerEpoch = ...
        height(trainRows);
end
distillation.TrainingSampling = trainingSampling;
distillation.GradientClippingScope = "trainable-only";
distillation.GradientAccumulationSteps = ...
    options.GradientAccumulationSteps;
distillation.NumGradientMicroBatches = microBatchCount;
distillation.NumOptimizerUpdatesPerEpoch = ceil( ...
    distillation.NumOptimizationSamplesPerEpoch/ ...
    options.GradientAccumulationSteps);
distillation.NumOptimizerUpdates = iteration;
distillation.NumFrozenGradientTensorsMaskedPerUpdate = ...
    frozenGradientTensorsPerUpdate;
distillation.OptimizerDiagnostics = optimizerDiagnostics;
distillation.TestEvaluated = false;
distillation.CreatedAt = datetime("now",TimeZone="local");
if strlength(options.SaveFile) > 0
    save(options.SaveFile,"distillation","-v7.3");
end
end

function [loss,hardLoss,softLoss,gradients,state] = ...
    knowledge_distillation_gradients( ...
    studentNet,teacherNet,X,T,classWeights,alpha,temperature, ...
    batchNormalizationMode)
if batchNormalizationMode == "frozen"
    [studentLogits,studentProbabilities] = predict( ...
        studentNet,X,Outputs=["fc","softmax"]);
    state = studentNet.State;
else
    [studentLogits,studentProbabilities,state] = forward( ...
        studentNet,X,Outputs=["fc","softmax"]);
end
hardLoss = crossentropy( ...
    studentProbabilities,T,classWeights,WeightsFormat="UC");
if alpha < 1
    teacherLogits = predict(teacherNet,X,Outputs="fc");
    studentSoft = softmax_with_temperature( ...
        studentLogits,temperature);
    teacherSoft = softmax_with_temperature( ...
        teacherLogits,temperature);
    softLoss = crossentropy(studentSoft,teacherSoft);
else
    softLoss = hardLoss*0;
end
loss = alpha*hardLoss+ ...
    (1-alpha)*temperature^2*softLoss;
gradients = dlgradient(loss,studentNet.Learnables);
end

function probabilities = softmax_with_temperature(logits,temperature)
channelDimension = finddim(logits,"C");
scaled = logits/temperature;
scaled = scaled-max(scaled,[],channelDimension);
exponentials = exp(scaled);
probabilities = exponentials./sum(exponentials,channelDimension);
end

function gradients = add_l2_gradients(net,gradients,coefficient)
if coefficient == 0
    return
end
for row = 1:height(gradients)
    factor = getL2Factor( ...
        net,gradients.Layer(row),gradients.Parameter(row));
    if factor == 0
        continue
    end
    matching = find( ...
        net.Learnables.Layer == gradients.Layer(row) & ...
        net.Learnables.Parameter == gradients.Parameter(row));
    assert(isscalar(matching),"NMA:DistillationLearnableMismatch", ...
        "Could not uniquely match a distillation gradient.");
    gradients.Value{row} = gradients.Value{row}+ ...
        coefficient*factor*net.Learnables.Value{matching};
end
end

function accumulator = accumulate_gradients(accumulator,gradients)
if isempty(accumulator)
    accumulator = gradients;
    return
end
assert(isequal(accumulator.Layer,gradients.Layer) && ...
    isequal(accumulator.Parameter,gradients.Parameter), ...
    "NMA:DistillationGradientTableMismatch", ...
    "Gradient tables changed within an accumulation group.");
for row = 1:height(gradients)
    accumulator.Value{row} = ...
        accumulator.Value{row}+gradients.Value{row};
end
end

function gradients = scale_gradients(gradients,scale)
for row = 1:height(gradients)
    gradients.Value{row} = gradients.Value{row}*scale;
end
end

function [gradients,numFrozenGradientTensors] = ...
    mask_frozen_gradients(net,gradients)
numFrozenGradientTensors = 0;
for row = 1:height(gradients)
    factor = getLearnRateFactor( ...
        net,gradients.Layer(row),gradients.Parameter(row));
    if factor == 0
        gradients.Value{row} = gradients.Value{row}*0;
        numFrozenGradientTensors = ...
            numFrozenGradientTensors+1;
    end
end
end

function [gradients,normValue] = clip_gradients(gradients,threshold)
normSquared = [];
for row = 1:height(gradients)
    value = extractdata(gradients.Value{row});
    contribution = sum(value.^2,"all");
    if isempty(normSquared)
        normSquared = contribution;
    else
        normSquared = normSquared+contribution;
    end
end
normValue = sqrt(double(gather(normSquared)));
if normValue > threshold
    scale = threshold/normValue;
    for row = 1:height(gradients)
        gradients.Value{row} = gradients.Value{row}*scale;
    end
end
end

function value = cpu_scalar(input)
value = extractdata(input);
if isa(value,"gpuArray")
    value = gather(value);
end
value = double(value);
end

function equal = state_tables_equal(first,second)
equal = isequal(string(first.Layer),string(second.Layer)) && ...
    isequal(string(first.Parameter),string(second.Parameter)) && ...
    height(first) == height(second);
if ~equal
    return
end
for row = 1:height(first)
    firstValue = extractdata(first.Value{row});
    secondValue = extractdata(second.Value{row});
    if ~isequal(firstValue,secondValue)
        equal = false;
        return
    end
end
end

function assert_frozen_learnables_equal(initialLearnables,net)
currentLearnables = net.Learnables;
assert(isequal(initialLearnables.Layer, ...
    currentLearnables.Layer) && ...
    isequal(initialLearnables.Parameter, ...
    currentLearnables.Parameter), ...
    "NMA:DistillationLearnableLayoutChanged", ...
    "The learnable tensor layout changed during training.");
for row = 1:height(currentLearnables)
    factor = getLearnRateFactor( ...
        net,currentLearnables.Layer(row), ...
        currentLearnables.Parameter(row));
    if factor ~= 0
        continue
    end
    initialValue = extractdata(initialLearnables.Value{row});
    currentValue = extractdata(currentLearnables.Value{row});
    if isa(initialValue,"gpuArray")
        initialValue = gather(initialValue);
    end
    if isa(currentValue,"gpuArray")
        currentValue = gather(currentValue);
    end
    assert(isequal(initialValue,currentValue), ...
        "NMA:DistillationFrozenLearnableChanged", ...
        "A frozen learnable tensor changed during training.");
end
end

function restore_gpu_state(previousDeterminism,previousGPUGenerator)
deep.gpu.deterministicAlgorithms(previousDeterminism);
gpurng(previousGPUGenerator);
end
