function [net,report] = ...
    adni_resnet3d18_initialize_imagenet(options)
%ADNI_RESNET3D18_INITIALIZE_IMAGENET Inflate ImageNet ResNet-18 to 3-D.
%
% The full-width [64 128 256 512] MATLAB ResNet-18 topology is used so
% every 2-D residual convolution and normalization has an exact 3-D
% counterpart. A k-by-k 2-D kernel is repeated along the third spatial
% dimension and divided by the 3-D kernel depth. Consequently, summing the
% inflated kernel over depth exactly recovers the source 2-D kernel. The
% RGB input kernels are first collapsed to one MRI channel by summation,
% matching the response obtained when one grayscale slice is replicated
% over the three RGB channels. The new three-class head remains randomly
% initialized.

arguments
    options.InputSize (1,4) double {mustBeInteger,mustBePositive} = ...
        [96 96 96 1]
    options.NumClasses (1,1) double {mustBeInteger,mustBePositive} = 3
    options.InternalNormalization (1,1) string = "batch"
end

assert(options.InputSize(4) == 1,"NMA:InflationRequiresSingleChannel", ...
    "ImageNet inflation currently supports one-channel MRI input.");
source = resnet18;
net = adni_resnet3d18_create( ...
    [64 128 256 512], ...
    InputSize=options.InputSize, ...
    NumClasses=options.NumClasses, ...
    InternalNormalization=options.InternalNormalization);

[sourceConvolutions,targetConvolutions] = convolution_mapping();
[sourceNormalizations,targetNormalizations] = normalization_mapping();
assert(numel(sourceConvolutions) == 20 && ...
    numel(targetConvolutions) == 20, ...
    "NMA:UnexpectedInflationMapping", ...
    "The ResNet-18 convolution mapping must contain 20 layers.");
assert(numel(sourceNormalizations) == 20 && ...
    numel(targetNormalizations) == 20, ...
    "NMA:UnexpectedInflationMapping", ...
    "The ResNet-18 normalization mapping must contain 20 layers.");

kernelRecoveryError = zeros(numel(sourceConvolutions),1);
kernelRecoveryTolerance = zeros(numel(sourceConvolutions),1);
transferredConvolutionParameters = 0;
for index = 1:numel(sourceConvolutions)
    sourceLayer = layer_by_name(source,sourceConvolutions(index));
    targetLayer = getLayer(net,targetConvolutions(index));
    assert(isa(sourceLayer,"nnet.cnn.layer.Convolution2DLayer") && ...
        isa(targetLayer,"nnet.cnn.layer.Convolution3DLayer"), ...
        "NMA:InflationLayerTypeMismatch", ...
        "Expected a 2-D to 3-D convolution mapping for %s.", ...
        sourceConvolutions(index));

    sourceWeights = single(sourceLayer.Weights);
    if sourceConvolutions(index) == "conv1"
        sourceWeights = sum(sourceWeights,3);
        sourceWeights = reshape(sourceWeights, ...
            [size(sourceWeights,1) size(sourceWeights,2) 1 1 ...
            size(sourceWeights,4)]);
    else
        sourceWeights = reshape(sourceWeights, ...
            [size(sourceWeights,1) size(sourceWeights,2) 1 ...
            size(sourceWeights,3) size(sourceWeights,4)]);
    end
    targetDepth = targetLayer.FilterSize(3);
    inflatedWeights = repmat( ...
        sourceWeights,[1 1 targetDepth 1 1])/single(targetDepth);
    assert(isequal(size(inflatedWeights),size(targetLayer.Weights)), ...
        "NMA:InflatedKernelSizeMismatch", ...
        "Inflated weights do not match target layer %s.", ...
        targetLayer.Name);
    recoveredWeights = sum(inflatedWeights,3);
    kernelRecoveryError(index) = max( ...
        abs(double(recoveredWeights(:))-double(sourceWeights(:))));
    kernelRecoveryTolerance(index) = ...
        16*double(eps("single"))*max( ...
        1,max(abs(double(sourceWeights(:)))));

    targetLayer.Weights = inflatedWeights;
    targetLayer.Bias = reshape( ...
        single(sourceLayer.Bias),size(targetLayer.Bias));
    net = replaceLayer(net,targetLayer.Name,targetLayer);
    transferredConvolutionParameters = ...
        transferredConvolutionParameters+numel(inflatedWeights)+ ...
        numel(targetLayer.Bias);
end

transferredNormalizationParameters = 0;
for index = 1:numel(sourceNormalizations)
    sourceLayer = layer_by_name(source,sourceNormalizations(index));
    targetLayer = getLayer(net,targetNormalizations(index));
    assert(isa(sourceLayer, ...
        "nnet.cnn.layer.BatchNormalizationLayer"), ...
        "NMA:InflationLayerTypeMismatch", ...
        "Expected ImageNet batch normalization at %s.", ...
        sourceNormalizations(index));
    if isa(targetLayer,"nnet.cnn.layer.BatchNormalizationLayer")
        targetLayer.Offset = reshape( ...
            single(sourceLayer.Offset),size(targetLayer.Offset));
        targetLayer.Scale = reshape( ...
            single(sourceLayer.Scale),size(targetLayer.Scale));
        targetLayer.TrainedMean = reshape( ...
            single(sourceLayer.TrainedMean), ...
            size(targetLayer.TrainedMean));
        targetLayer.TrainedVariance = reshape( ...
            single(sourceLayer.TrainedVariance), ...
            size(targetLayer.TrainedVariance));
        transferredNormalizationParameters = ...
            transferredNormalizationParameters+ ...
            numel(targetLayer.Offset)+numel(targetLayer.Scale)+ ...
            numel(targetLayer.TrainedMean)+ ...
            numel(targetLayer.TrainedVariance);
    elseif isa(targetLayer, ...
            "nnet.cnn.layer.GroupNormalizationLayer")
        targetLayer.Offset = reshape( ...
            single(sourceLayer.Offset),size(targetLayer.Offset));
        targetLayer.Scale = reshape( ...
            single(sourceLayer.Scale),size(targetLayer.Scale));
        transferredNormalizationParameters = ...
            transferredNormalizationParameters+ ...
            numel(targetLayer.Offset)+numel(targetLayer.Scale);
    else
        error("NMA:InflationLayerTypeMismatch", ...
            "Unsupported target normalization at %s.",targetLayer.Name);
    end
    net = replaceLayer(net,targetLayer.Name,targetLayer);
end

net = initialize(net);
assert(net.Initialized,"NMA:InflatedNetworkUninitialized", ...
    "The inflated 3-D network must be initialized.");
postInitializationRecoveryError = zeros( ...
    numel(sourceConvolutions),1);
for index = 1:numel(sourceConvolutions)
    sourceLayer = layer_by_name(source,sourceConvolutions(index));
    sourceWeights = single(sourceLayer.Weights);
    if sourceConvolutions(index) == "conv1"
        sourceWeights = sum(sourceWeights,3);
        sourceWeights = reshape(sourceWeights, ...
            [size(sourceWeights,1) size(sourceWeights,2) 1 1 ...
            size(sourceWeights,4)]);
    else
        sourceWeights = reshape(sourceWeights, ...
            [size(sourceWeights,1) size(sourceWeights,2) 1 ...
            size(sourceWeights,3) size(sourceWeights,4)]);
    end
    targetLayer = getLayer(net,targetConvolutions(index));
    recoveredWeights = sum(single(targetLayer.Weights),3);
    postInitializationRecoveryError(index) = max( ...
        abs(double(recoveredWeights(:))-double(sourceWeights(:))));
end
spec = nma_resnet3d18_spec(net);
assert(isequal(spec.BaselineWidths,[64;128;256;512]), ...
    "NMA:InflatedWidthMismatch", ...
    "ImageNet inflation requires full ResNet-18 widths.");
assert(all(kernelRecoveryError <= kernelRecoveryTolerance), ...
    "NMA:InflationRecoveryFailure", ...
    "Inflated kernels do not recover the source 2-D kernels.");
assert(all(postInitializationRecoveryError <= ...
    kernelRecoveryTolerance), ...
    "NMA:InflationInitializationChangedWeights", ...
    "Network initialization changed the transferred kernels.");
assert(all(cellfun(@(value) all(isfinite(extractdata(value)),"all"), ...
    net.Learnables.Value)),"NMA:NonfiniteInflatedWeights", ...
    "The inflated network contains nonfinite learnable parameters.");

report = struct;
report.Method = "ImageNet-2D-to-3D-kernel-inflation";
report.SourceNetwork = "MATLAB ResNet-18 ImageNet weights";
report.SourceConvolutionNames = sourceConvolutions;
report.TargetConvolutionNames = targetConvolutions;
report.SourceNormalizationNames = sourceNormalizations;
report.TargetNormalizationNames = targetNormalizations;
report.Widths = spec.BaselineWidths;
report.InputSize = spec.InputSize;
report.InternalNormalization = lower(options.InternalNormalization);
report.RGBCollapse = "sum";
report.DepthInflation = "repeat-and-divide-by-kernel-depth";
report.MaximumKernelRecoveryError = max(kernelRecoveryError);
report.MaximumPostInitializationRecoveryError = ...
    max(postInitializationRecoveryError);
report.MaximumKernelRecoveryTolerance = ...
    max(kernelRecoveryTolerance);
report.MaximumRecoveryErrorToToleranceRatio = max([ ...
    kernelRecoveryError./kernelRecoveryTolerance; ...
    postInitializationRecoveryError./kernelRecoveryTolerance]);
report.TransferredConvolutionParameters = ...
    transferredConvolutionParameters;
report.TransferredNormalizationParameters = ...
    transferredNormalizationParameters;
report.NewClassifierOutputSize = getLayer(net,"fc").OutputSize;
report.NewClassifierParameters = numel(getLayer(net,"fc").Weights)+ ...
    numel(getLayer(net,"fc").Bias);
report.TotalLearnableParameters = ...
    sum(cellfun(@numel,net.Learnables.Value));
report.CreatedAt = datetime("now",TimeZone="local");
end

function layer = layer_by_name(net,name)
names = string({net.Layers.Name});
index = find(names == name,1);
assert(~isempty(index),"NMA:MissingImageNetLayer", ...
    "ImageNet ResNet-18 does not contain layer %s.",name);
layer = net.Layers(index);
end

