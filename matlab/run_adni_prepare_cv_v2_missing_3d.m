%% Prepare only the 382 canonical visits missing from the existing 3-D pool.
addpath(fileparts(mfilename("fullpath")));

projectRoot = fileparts(fileparts(mfilename("fullpath")));
splitManifest = fullfile( ...
    projectRoot,"adni_work","adni_3d_cv_v2", ...
    "missing_3d_split.csv");
outputRoot = fullfile( ...
    projectRoot,"adni_work","adni_3d_cv_v2", ...
    "missing_volumes");
assert(isfile(splitManifest), ...
    "NMA:MissingCVV2PreparationPlan", ...
    "Run adni_build_cv_v2_manifests.py --stage plan first.");
source = readtable( ...
    splitManifest,Delimiter=",",TextType="string", ...
    VariableNamingRule="preserve");
assert(height(source) == 382 && ...
    numel(unique(source.Subject)) == 191 && ...
    all(groupcounts(source.Subject) == 2) && ...
    all(isfile(source.("NIfTI Path"))), ...
    "NMA:InvalidCVV2MissingVolumePlan", ...
    "The CV v2 missing-volume plan violates its frozen contract.");

report = adni_prepare_3d_dataset( ...
    splitManifest,outputRoot,OutputSize=[96 96 96], ...
    Overwrite=false,Verbose=true);
assert(report.NumVolumes == 382 && ...
    isequal(report.OutputSize,[96 96 96]), ...
    "NMA:InvalidCVV2PreparationReport", ...
    "CV v2 missing-volume preparation did not complete.");
save(fullfile(projectRoot,"adni_work","adni_3d_cv_v2", ...
    "missing_3d_preparation_report.mat"),"report","-v7.3");
fprintf("ADNI_RESNET3D18_CV_V2_MISSING_PREPARATION_PASS\n");
