%% Aggregate 25 independent v4 cell audits and gate the outer test.
addpath(fileparts(mfilename("fullpath")));

scriptDirectory = fileparts(mfilename("fullpath"));
projectRoot = fileparts(scriptDirectory);
workRoot = fullfile(projectRoot,"adni_work");
trainingRoot = fullfile( ...
    workRoot,"adni_3d_cv_v4", ...
    "locked_internal_validation_training");
auditCellsRoot = fullfile( ...
    workRoot,"adni_3d_cv_v4","pretest_audit_cells");
preflightFile = fullfile( ...
    workRoot,"adni_3d_cv_v4","full_validation_preflight", ...
    "v4_full_validation_preflight.mat");
runFile = fullfile( ...
    trainingRoot,"v4_validation_training_result.mat");
sourceFile = string([mfilename("fullpath") ".m"]);
assert(isfile(preflightFile) && isfile(runFile), ...
    "NMA:MissingCVV4PreTestAuditEnvelope", ...
    "The full preflight and validation-training run are required.");

folds = (1:5).';
seeds = (20260820:20260824).';
numCells = numel(folds)*numel(seeds);
auditFiles = strings(numCells,1);
foldColumn = zeros(numCells,1);
seedColumn = zeros(numCells,1);
cellIndex = 0;
for foldIndex = 1:numel(folds)
    for seedIndex = 1:numel(seeds)
        cellIndex = cellIndex+1;
        foldColumn(cellIndex) = folds(foldIndex);
        seedColumn(cellIndex) = seeds(seedIndex);
        auditFiles(cellIndex) = fullfile( ...
            auditCellsRoot,"fold_"+folds(foldIndex), ...
            "seed_"+seeds(seedIndex),"audit_cell_result.mat");
    end
end
assert(all(isfile(auditFiles)), ...
    "NMA:MissingCVV4PreTestCellAudit", ...
    "All 25 independent v4 cell audits must finish before aggregation.");

inputNames = [ ...
    "full_preflight";"full_training_run"; ...
    "aggregate_audit_source"; ...
    "cell_audit_"+compose("%02d",(1:numCells).')];
inputPaths = [preflightFile;runFile;sourceFile;auditFiles];
inputMetadata = collect_file_metadata(inputNames,inputPaths);
preflightSource = load(preflightFile,"preflight");
runSource = load(runFile,"run");
preflight = preflightSource.preflight;
runResult = runSource.run;
validate_envelope(preflight,runResult,preflightFile);

records = repmat(empty_audit_record(),numCells,1);
summaryParts = cell(numCells,1);
for index = 1:numCells
    source = load(auditFiles(index),"audit");
    audit = source.audit;
    assert(audit.Passed && ...
        audit.Fold == foldColumn(index) && ...
        audit.Seed == seedColumn(index) && ...
        audit.InitializationReproduced && ...
        audit.TrainingArtifactsValidated == 3 && ...
        audit.SupportArtifactsValidated == 2 && ...
        audit.CalibrationReproduced && ...
        audit.AllocationReproduced && audit.SurgeryReproduced && ...
        audit.AllValidationPredictionsReproduced && ...
        audit.NoPostHocSelection && ...
        ~audit.PredictiveMetricsForInference && ...
        ~audit.OuterTestPredictionsComputed && ...
        ~audit.OuterTestEvaluated && audit.OuterTestSealed && ...
        height(audit.VerifiedSummary) == 3, ...
        "NMA:InvalidCVV4PreTestCellAudit", ...
        "Cell audit %d is stale or incomplete.",index);
    validate_metadata(audit.InputMetadata);
    records(index) = make_record(index,auditFiles(index),audit);
    cellSummary = addvars( ...
        audit.VerifiedSummary, ...
        repmat(audit.Fold,3,1),repmat(audit.Seed,3,1), ...
        'Before',1,'NewVariableNames',["Fold","Seed"]);
    summaryParts{index} = cellSummary;
end

verifiedSummary = vertcat(summaryParts{:});
assert(height(verifiedSummary) == 75 && ...
    sum(verifiedSummary.Method == "dense") == 25 && ...
    sum(verifiedSummary.Method == "proportional") == 25 && ...
    sum(verifiedSummary.Method == "multi-resource-NMA") == 25 && ...
    isequal(verifiedSummary,runResult.PerCellMethodSummary) && ...
    all([records.Passed].') && ...
    sum([records.TrainingArtifactsValidated]) == 75 && ...
    sum([records.SupportArtifactsValidated]) == 50 && ...
    all([records.CalibrationMaximumError].' <= 1e-7), ...
    "NMA:IncompleteCVV4PreTestAudit", ...
    "The 25-cell v4 pre-test audit is incomplete or inconsistent.");

validation = struct;
validation.Design = ...
    "independent v4 complete-validation pre-test authorization audit";
validation.ProtocolFile = fullfile( ...
    projectRoot,"ADNI_NMA_CV_V4_LOCKED_INTERNAL_VALIDATION_PROTOCOL.md");
validation.PreflightFile = preflightFile;
validation.TrainingRunFile = runFile;
validation.InputMetadata = inputMetadata;
validation.Folds = folds;
validation.Seeds = seeds;
validation.ExecutionOrder = "fold-major-then-seed-major";
validation.Records = records;
validation.VerifiedPerCellMethodSummary = verifiedSummary;
validation.CompletedCellAudits = 25;
validation.TrainingArtifactsValidated = 75;
validation.SupportArtifactsValidated = 50;
validation.InitializationsReproduced = 25;
validation.CalibrationsReproduced = 25;
validation.AllocationsReproduced = 25;
validation.SurgeriesReproduced = 50;
validation.ValidationPredictionSetsReproduced = 75;
validation.AllFoldsSeedsMethodsRetained = true;
validation.NoPostHocSelection = true;
validation.PredictiveMetricsForInference = false;
validation.OuterTestPredictionsComputed = false;
validation.OuterTestEvaluated = false;
validation.OuterTestSealed = true;
validation.AtomicOuterTestReleaseRequired = true;
validation.Phase4OuterTestEvaluationAuthorized = true;
validation.Passed = true;
validation.ValidatedAt = datetime("now",TimeZone="local");

outputRoot = fullfile( ...
    workRoot,"adni_3d_cv_v4","pretest_audit");
if ~isfolder(outputRoot)
    mkdir(outputRoot);
end
outputFile = fullfile( ...
    outputRoot,"v4_validation_training_pretest_audit.mat");
atomic_save(outputFile,"validation",validation);
writetable(struct2table(records),fullfile( ...
    outputRoot,"v4_pretest_audit_cells.csv"),Encoding="UTF-8");
writetable(verifiedSummary,fullfile( ...
    outputRoot,"v4_pretest_verified_per_cell_method.csv"), ...
    Encoding="UTF-8");
disp(struct2table(records));
fprintf( ...
    ["CV_V4_PRETEST_AUDIT cells %d trainingArtifacts %d " ...
    "validationPredictions %d testSealed %d\n"], ...
    validation.CompletedCellAudits, ...
    validation.TrainingArtifactsValidated, ...
    validation.ValidationPredictionSetsReproduced, ...
    validation.OuterTestSealed);
fprintf( ...
    "ADNI_RESNET3D18_CV_V4_VALIDATION_PRETEST_AUDIT_PASS\n");

function validate_envelope(preflight,runResult,preflightFile)
assert(preflight.Passed && ...
    preflight.Phase2ValidationTrainingAuthorized && ...
    preflight.SmokeValidationPassed && ...
    preflight.NumCells == 25 && preflight.OuterTestSealed && ...
    ~preflight.OuterTestPredictionsComputed && ...
    ~preflight.OuterTestEvaluated, ...
    "NMA:InvalidCVV4PreTestPreflight", ...
    "The full-validation preflight envelope is invalid.");
validate_metadata(preflight.InputMetadata);
assert(runResult.Passed && ...
    runResult.ReadyForIndependentPreTestAudit && ...
    runResult.CompletedCells == 25 && ...
    runResult.CompletedDenseTeachers == 25 && ...
    runResult.CompletedCompressedStudents == 50 && ...
    runResult.TotalNetworks == 75 && ...
    stamp_matches(runResult.PreflightStamp,file_stamp(preflightFile)) && ...
    ~runResult.PredictiveMetricsForInference && ...
    ~runResult.OuterTestPredictionsComputed && ...
    ~runResult.OuterTestEvaluated && runResult.OuterTestSealed, ...
    "NMA:InvalidCVV4PreTestTrainingRun", ...
    "The full validation-training envelope is invalid.");
end

function validate_metadata(metadata)
for index = 1:height(metadata)
    information = dir(metadata.Path(index));
    assert(isscalar(information) && ...
        information.bytes == metadata.Bytes(index) && ...
        information.datenum == metadata.Modified(index), ...
        "NMA:ChangedCVV4PreTestInput", ...
        "A pre-test audit input changed: %s",metadata.Path(index));
end
end

function record = empty_audit_record()
record = struct( ...
    "CellIndex",NaN,"Fold",NaN,"Seed",NaN, ...
    "AuditFile","","AuditFileBytes",NaN, ...
    "AuditFileModified",NaN,"TrainingArtifactsValidated",NaN, ...
    "SupportArtifactsValidated",NaN, ...
    "CalibrationMaximumError",NaN, ...
    "NMAWidth1",NaN,"NMAWidth2",NaN, ...
    "NMAWidth3",NaN,"NMAWidth4",NaN, ...
    "OuterTestEvaluated",false,"Passed",false);
end

function record = make_record(index,auditFile,audit)
stamp = file_stamp(auditFile);
record = empty_audit_record();
record.CellIndex = index;
record.Fold = audit.Fold;
record.Seed = audit.Seed;
record.AuditFile = auditFile;
record.AuditFileBytes = stamp.Bytes;
record.AuditFileModified = stamp.Modified;
record.TrainingArtifactsValidated = audit.TrainingArtifactsValidated;
record.SupportArtifactsValidated = audit.SupportArtifactsValidated;
record.CalibrationMaximumError = audit.CalibrationMaximumError;
record.NMAWidth1 = audit.NMAWidths(1);
record.NMAWidth2 = audit.NMAWidths(2);
record.NMAWidth3 = audit.NMAWidths(3);
record.NMAWidth4 = audit.NMAWidths(4);
record.OuterTestEvaluated = false;
record.Passed = audit.Passed;
end

function metadata = collect_file_metadata(names,paths)
bytes = zeros(numel(paths),1);
modified = zeros(numel(paths),1);
for index = 1:numel(paths)
    information = dir(paths(index));
    assert(isscalar(information), ...
        "NMA:CVV4PreTestMetadataFailure", ...
        "Could not inspect a v4 pre-test input.");
    bytes(index) = information.bytes;
    modified(index) = information.datenum;
end
metadata = table( ...
    names,paths,bytes,modified, ...
    VariableNames=["Name","Path","Bytes","Modified"]);
end

function stamp = file_stamp(path)
information = dir(path);
assert(isscalar(information), ...
    "NMA:CVV4PreTestStampFailure", ...
    "Could not inspect v4 pre-test file %s.",path);
stamp = struct( ...
    "Path",string(path),"Bytes",information.bytes, ...
    "Modified",information.datenum);
end

function matches = stamp_matches(first,second)
matches = first.Path == second.Path && ...
    first.Bytes == second.Bytes && ...
    first.Modified == second.Modified;
end

function atomic_save(path,variableName,value)
partialFile = path+".partial";
payload = struct;
payload.(variableName) = value;
save(partialFile,"-struct","payload","-v7.3");
movefile(partialFile,path,"f");
end
