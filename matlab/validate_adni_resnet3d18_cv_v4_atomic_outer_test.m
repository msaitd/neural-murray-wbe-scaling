%% Independently validate the complete saved v4 atomic outer-test release.
addpath(fileparts(mfilename("fullpath")));

scriptDirectory = fileparts(mfilename("fullpath"));
projectRoot = fileparts(scriptDirectory);
workRoot = fullfile(projectRoot,"adni_work");
preflightFile = fullfile( ...
    workRoot,"adni_3d_cv_v4","phase4_atomic_preflight", ...
    "v4_phase4_atomic_preflight.mat");
authorizationFile = fullfile( ...
    workRoot,"adni_3d_cv_v4","pretest_audit", ...
    "v4_phase3_recovery_authorization.mat");
releaseFile = fullfile( ...
    workRoot,"adni_3d_cv_v4","atomic_outer_test", ...
    "v4_atomic_outer_test_release.mat");
sourceFile = string(mfilename("fullpath"))+".m";
assert(all(isfile([ ...
    string(preflightFile);string(authorizationFile); ...
    string(releaseFile);sourceFile])), ...
    "NMA:MissingCVV4OuterValidationInput", ...
    "The Phase-4 preflight, authorization, and release are required.");

preflightSource = load(preflightFile,"preflight");
authorizationSource = load(authorizationFile,"authorization");
releaseSource = load(releaseFile,"release");
preflight = preflightSource.preflight;
authorization = authorizationSource.authorization;
release = releaseSource.release;
assert(preflight.Passed && preflight.Phase4AtomicOuterTestAuthorized && ...
    authorization.Passed && ...
    authorization.Phase4OuterTestEvaluationAuthorized && ...
    release.Passed && release.AtomicBatch && ...
    release.CompletedCells == 25 && release.CompletedEvaluations == 75 && ...
    release.CompletedPredictionRows == 9585 && ...
    release.UniqueParticipantsPerSeedMethod == 639 && ...
    release.NoPostHocSelection && release.AllMethodsFoldsSeedsRetained && ...
    release.OuterTestPredictionsComputed && release.OuterTestEvaluated && ...
    ~release.OuterTestSealed && ...
    stamp_matches(release.Phase4PreflightStamp,file_stamp(preflightFile)) && ...
    stamp_matches(release.Phase3AuthorizationStamp, ...
    file_stamp(authorizationFile)), ...
    "NMA:InvalidCVV4OuterValidationEnvelope", ...
    "The atomic Phase-4 release envelope is invalid.");
validate_metadata(preflight.InputMetadata, ...
    "NMA:ChangedCVV4OuterValidationPreflightInput");
validate_metadata(authorization.InputMetadata, ...
    "NMA:ChangedCVV4OuterValidationAuthorizationInput");
validate_metadata(release.InputMetadata, ...
    "NMA:ChangedCVV4OuterValidationReleaseInput");

predictions = release.OuterPredictions;
summary = release.PerCellMethodSummary;
validate_prediction_grid(predictions,release.Seeds,release.Methods);
assert(height(summary) == 75 && ...
    isequal(summary.EvaluationIndex,(1:75).'), ...
    "NMA:InvalidCVV4OuterValidationSummary", ...
    "The atomic Phase-4 summary is incomplete or out of order.");

maximumMetricError = 0;
for index = 1:height(summary)
    record = summary(index,:);
    rows = predictions( ...
        predictions.Fold == record.Fold & ...
        predictions.Seed == record.Seed & ...
        predictions.Method == record.Method,:);
    scores = rows{:,{'ScoreAD','ScoreCN','ScoreMCI'}};
    [metrics,confusion,predictedGroup] = ...
        adni_resnet3d18_cv_v4_metrics(rows.TrueGroup,scores);
    assert(isequal(predictedGroup,rows.PredictedGroup), ...
        "NMA:ChangedCVV4OuterValidationPrediction", ...
        "A saved predicted class does not match its saved scores.");
    recomputed = [ ...
        metrics.Accuracy,metrics.BalancedAccuracy,metrics.MacroF1, ...
        metrics.RecallAD,metrics.RecallCN,metrics.RecallMCI, ...
        metrics.MacroAUROC,metrics.NegativeLogLikelihood, ...
        metrics.BrierScore,metrics.ECE];
    stored = record{1,{ ...
        'Accuracy','BalancedAccuracy','MacroF1','RecallAD','RecallCN', ...
        'RecallMCI','MacroAUROC','NegativeLogLikelihood','BrierScore','ECE'}};
    maximumMetricError = max(maximumMetricError,max(abs(recomputed-stored)));
    storedConfusion = [ ...
        record.ConfusionADAD,record.ConfusionADCN,record.ConfusionADMCI; ...
        record.ConfusionCNAD,record.ConfusionCNCN,record.ConfusionCNMCI; ...
        record.ConfusionMCIAD,record.ConfusionMCICN, ...
        record.ConfusionMCIMCI];
    widths = record{1,{'Width1','Width2','Width3','Width4'}}.';
    expectedParameters = nma_resnet3d18_resource( ...
        widths,Resource="parameters",NumClasses=3);
    expectedMACs = nma_resnet3d18_resource( ...
        widths,Resource="macs",NumClasses=3);
    expectedActivation = nma_resnet3d18_resource( ...
        widths,Resource="activation",NumClasses=3);
    artifactStamp = file_stamp(record.ArtifactFile);
    assert(max(abs(recomputed-stored)) <= 1e-12 && ...
        isequal(confusion,storedConfusion) && ...
        record.ParameterCount == expectedParameters && ...
        record.MACs == expectedMACs && ...
        record.ActivationProxy == expectedActivation && ...
        record.ArtifactBytes == artifactStamp.Bytes && ...
        record.ArtifactModified == artifactStamp.Modified && ...
        record.OuterTestEvaluated && record.Passed, ...
        "NMA:CVV4OuterValidationMismatch", ...
        "Atomic outer-test record %d did not reproduce.",index);
end

inputNames = [ ...
    "phase4_preflight";"phase3_authorization"; ...
    "atomic_outer_release";"postrelease_validator_source"];
inputPaths = [ ...
    string(preflightFile);string(authorizationFile); ...
    string(releaseFile);sourceFile];
inputMetadata = collect_file_metadata(inputNames,inputPaths);
validation = struct;
validation.Design = ...
    "independent metric and integrity validation of atomic v4 outer release";
validation.InputMetadata = inputMetadata;
validation.ReleaseFile = releaseFile;
validation.CompletedEvaluations = 75;
validation.CompletedPredictionRows = 9585;
validation.UniqueParticipantsPerSeedMethod = 639;
validation.MetricsRecomputed = 75;
validation.MaximumMetricError = maximumMetricError;
validation.AllPredictionClassesReproduced = true;
validation.AllConfusionMatricesReproduced = true;
validation.AllAnalyticalResourcesReproduced = true;
validation.AllArtifactStampsValid = true;
validation.NoPostHocSelection = true;
validation.OuterTestPredictionsComputed = true;
validation.OuterTestEvaluated = true;
validation.ReadyForLockedStatisticalAnalysis = true;
validation.Passed = true;
validation.ValidatedAt = datetime("now",TimeZone="local");

outputRoot = fullfile( ...
    workRoot,"adni_3d_cv_v4","atomic_outer_test_validation");
if ~isfolder(outputRoot)
    mkdir(outputRoot);
end
outputFile = fullfile(outputRoot,"v4_atomic_outer_test_validation.mat");
atomic_save(outputFile,"validation",validation);
atomic_writetable(inputMetadata,fullfile( ...
    outputRoot,"v4_atomic_outer_test_validation_inputs.csv"));
fprintf( ...
    "CV_V4_ATOMIC_OUTER_VALIDATION evaluations %d predictionRows %d maximumMetricError %.9g\n", ...
    validation.CompletedEvaluations,validation.CompletedPredictionRows, ...
    validation.MaximumMetricError);
fprintf("ADNI_RESNET3D18_CV_V4_ATOMIC_OUTER_TEST_VALIDATION_PASS\n");

function validate_prediction_grid(predictions,seeds,methods)
assert(height(predictions) == 9585 && ...
    all(ismember(predictions.TrueGroup,["AD";"CN";"MCI"])) && ...
    all(ismember(predictions.PredictedGroup,["AD";"CN";"MCI"])) && ...
    all(isfinite(predictions{:,{'ScoreAD','ScoreCN','ScoreMCI'}}),"all"), ...
    "NMA:InvalidCVV4OuterValidationPredictionGrid", ...
    "The saved outer prediction grid is invalid.");
referenceTruth = unique(predictions(:,["Subject","TrueGroup"]),"rows");
assert(height(referenceTruth) == 639, ...
    "NMA:InvalidCVV4OuterValidationTruth", ...
    "The saved release does not contain 639 consistent participants.");
for seedIndex = 1:numel(seeds)
    for methodIndex = 1:numel(methods)
        rows = predictions( ...
            predictions.Seed == seeds(seedIndex) & ...
            predictions.Method == methods(methodIndex),:);
        assert(height(rows) == 639 && ...
            numel(unique(rows.Subject)) == 639 && ...
            isequal(sortrows(rows(:,["Subject","TrueGroup"])), ...
            sortrows(referenceTruth)), ...
            "NMA:InvalidCVV4OuterValidationSeedMethod", ...
            "A seed-method participant grid is incomplete.");
    end
end
end

function metadata = collect_file_metadata(names,paths)
bytes = zeros(numel(paths),1);
modified = zeros(numel(paths),1);
for index = 1:numel(paths)
    information = dir(paths(index));
    assert(isscalar(information), ...
        "NMA:CVV4OuterValidationMetadataFailure", ...
        "Could not inspect a post-release validation input.");
    bytes(index) = information.bytes;
    modified(index) = information.datenum;
end
metadata = table( ...
    names,paths,bytes,modified, ...
    VariableNames=["Name","Path","Bytes","Modified"]);
end

function validate_metadata(metadata,errorIdentifier)
for index = 1:height(metadata)
    information = dir(metadata.Path(index));
    assert(isscalar(information) && ...
        information.bytes == metadata.Bytes(index) && ...
        information.datenum == metadata.Modified(index), ...
        errorIdentifier, ...
        "A post-release validation input changed: %s", ...
        metadata.Path(index));
end
end

function stamp = file_stamp(path)
information = dir(path);
assert(isscalar(information),"NMA:CVV4OuterValidationStampFailure", ...
    "Could not inspect post-release file %s.",path);
stamp = struct( ...
    "Path",string(path),"Bytes",information.bytes, ...
    "Modified",information.datenum);
end

function matches = stamp_matches(first,second)
matches = first.Path == second.Path && ...
    first.Bytes == second.Bytes && first.Modified == second.Modified;
end

function atomic_save(path,variableName,value)
partialFile = path+".partial";
payload = struct;
payload.(variableName) = value;
save(partialFile,"-struct","payload","-v7.3");
movefile(partialFile,path,"f");
end

function atomic_writetable(value,path)
partialFile = path+".partial.csv";
writetable(value,partialFile,FileType="text",Delimiter=",", ...
    Encoding="UTF-8");
movefile(partialFile,path,"f");
end
