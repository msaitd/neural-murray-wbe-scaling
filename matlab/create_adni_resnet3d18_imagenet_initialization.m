%% Create the immutable raw ImageNet-inflated three-dimensional ResNet-18.
addpath(fileparts(mfilename("fullpath")));

scriptDirectory = fileparts(mfilename("fullpath"));
projectRoot = fileparts(scriptDirectory);
workRoot = fullfile(projectRoot,"adni_work");
if ~isfolder(workRoot)
    mkdir(workRoot);
end

outputFile = fullfile( ...
    workRoot,"adni_resnet3d18_imagenet_initialization.mat");
assert(~isfile(outputFile), ...
    "NMA:InitializationAlreadyExists", ...
    ["The immutable initialization already exists. Remove it only " ...
     "after independently confirming that a fresh snapshot is intended."]);

[net,report] = adni_resnet3d18_initialize_imagenet( ...
    InputSize=[96 96 96 1],NumClasses=3, ...
    InternalNormalization="batch");

bench = struct;
bench.ParameterCount = nma_resnet3d18_resource( ...
    [64 128 256 512],Resource="parameters",NumClasses=3);
bench.MACs = nma_resnet3d18_resource( ...
    [64 128 256 512],Resource="macs",NumClasses=3);
bench.ActivationProxy = nma_resnet3d18_resource( ...
    [64 128 256 512],Resource="activation",NumClasses=3);

assert(bench.ParameterCount == 33166339 && ...
    bench.MACs == 13249807872 && ...
    bench.ActivationProxy == 5875200, ...
    "NMA:InitializationResourceMismatch", ...
    "The raw initialization resource contract changed.");

partialFile = outputFile+".partial";
save(partialFile,"net","report","bench","-v7.3");
movefile(partialFile,outputFile,"f");
fprintf("ADNI_RESNET3D18_IMAGENET_INITIALIZATION_PASS %s\n",outputFile);
