%% Link the recovery amendment to the completed canonical Phase-3 audit.
addpath(fileparts(mfilename("fullpath")));

scriptDirectory = fileparts(mfilename("fullpath"));
projectRoot = fileparts(scriptDirectory);
workRoot = fullfile(projectRoot,"adni_work");
recoveryPreflightFile = fullfile( ...
    workRoot,"adni_3d_cv_v4","phase3_recovery_preflight", ...
    "v4_phase3_recovery_preflight.mat");
auditFile = fullfile( ...
    workRoot,"adni_3d_cv_v4","pretest_audit", ...
    "v4_validation_training_pretest_audit.mat");
sourceFile = string(mfilename("fullpath"))+".m";
assert(isfile(recoveryPreflightFile) && isfile(auditFile), ...
    "NMA:MissingCVV4Phase3RecoveryAuthorizationInput", ...
    "Recovery preflight and completed Phase-3 audit are required.");

recoverySource = load(recoveryPreflightFile,"recovery");
auditSource = load(auditFile,"validation");
recovery = recoverySource.recovery;
validation = auditSource.validation;
assert(recovery.Passed && recovery.Phase3RecoveryAuditAuthorized && ...
    recovery.OnlyPermittedSourceSubstitutions && ...
    recovery.OriginalStampedSourcesUnchanged && ...
    recovery.TrainingArtifactsUnchanged && ...
    recovery.ValidationAuditOnly && ...
    ~recovery.OuterTestPredictionsComputed && ...
    ~recovery.OuterTestEvaluated && recovery.OuterTestSealed, ...
    "NMA:InvalidCVV4Phase3RecoveryPreflight", ...
    "The Phase-3 recovery preflight is invalid.");
validate_metadata(recovery.InputMetadata, ...
    "NMA:ChangedCVV4Phase3RecoveryPreflightInput");
assert(validation.Passed && ...
    validation.Phase4OuterTestEvaluationAuthorized && ...
    validation.CompletedCellAudits == 25 && ...
    validation.TrainingArtifactsValidated == 75 && ...
    validation.SupportArtifactsValidated == 50 && ...
    validation.ValidationPredictionSetsReproduced == 75 && ...
    validation.AllFoldsSeedsMethodsRetained && ...
    validation.NoPostHocSelection && ...
    ~validation.PredictiveMetricsForInference && ...
    ~validation.OuterTestPredictionsComputed && ...
    ~validation.OuterTestEvaluated && validation.OuterTestSealed, ...
    "NMA:InvalidCVV4Phase3RecoveryAudit", ...
    "The completed Phase-3 audit is invalid.");
validate_metadata(validation.InputMetadata, ...
    "NMA:ChangedCVV4Phase3RecoveryAuditInput");

aggregateSourceRow = validation.InputMetadata( ...
    validation.InputMetadata.Name == "aggregate_audit_source",:);
expectedAggregateSource = fullfile( ...
    scriptDirectory, ...
    "validate_adni_resnet3d18_cv_v4_validation_training_recovery.m");
assert(height(aggregateSourceRow) == 1 && ...
    string(aggregateSourceRow.Path) == string(expectedAggregateSource), ...
    "NMA:InvalidCVV4Phase3RecoveryAggregateSource", ...
    "The canonical Phase-3 audit was not made by the recovery aggregator.");

expectedAuditorSource = fullfile( ...
    scriptDirectory, ...
    "adni_audit_resnet3d18_cv_v4_validation_cell_recovery.m");
for index = 1:numel(validation.Records)
    cellSource = load(validation.Records(index).AuditFile,"audit");
    audit = cellSource.audit;
    sourceRow = audit.InputMetadata( ...
        audit.InputMetadata.Name == "audit_source",:);
    assert(height(sourceRow) == 1 && ...
        string(sourceRow.Path) == string(expectedAuditorSource) && ...
        audit.Passed && ~audit.OuterTestEvaluated && ...
        audit.OuterTestSealed, ...
        "NMA:InvalidCVV4Phase3RecoveryCellSource", ...
        "Cell audit %d was not made by the recovery auditor.",index);
end

inputNames = ["recovery_preflight";"canonical_phase3_audit"; ...
    "recovery_authorization_source"];
inputPaths = [string(recoveryPreflightFile);string(auditFile);sourceFile];
inputMetadata = collect_file_metadata(inputNames,inputPaths);
authorization = struct;
authorization.Design = ...
    "atomic v4 Phase-3 recovery authorization for sealed Phase 4";
authorization.RecoveryPreflightFile = recoveryPreflightFile;
authorization.CanonicalPhase3AuditFile = auditFile;
authorization.InputMetadata = inputMetadata;
authorization.CompletedCellAudits = 25;
authorization.ValidationPredictionSetsReproduced = 75;
authorization.OnlyPermittedRecoveryApplied = true;
authorization.TrainingArtifactsUnchanged = true;
authorization.NoPostHocSelection = true;
authorization.OuterTestPredictionsComputed = false;
authorization.OuterTestEvaluated = false;
authorization.OuterTestSealed = true;
authorization.AtomicOuterTestReleaseRequired = true;
authorization.Phase4OuterTestEvaluationAuthorized = true;
authorization.Passed = true;
authorization.AuthorizedAt = datetime("now",TimeZone="local");

outputRoot = fullfile(workRoot,"adni_3d_cv_v4","pretest_audit");
outputFile = fullfile( ...
    outputRoot,"v4_phase3_recovery_authorization.mat");
atomic_save(outputFile,"authorization",authorization);
writetable(inputMetadata,fullfile( ...
    outputRoot,"v4_phase3_recovery_authorization_inputs.csv"), ...
    Encoding="UTF-8");
fprintf( ...
    "CV_V4_PHASE3_RECOVERY_AUTHORIZATION cells %d "+ ...
    "validationPredictions %d testSealed %d\n", ...
    authorization.CompletedCellAudits, ...
    authorization.ValidationPredictionSetsReproduced, ...
    authorization.OuterTestSealed);
fprintf("ADNI_RESNET3D18_CV_V4_PHASE3_RECOVERY_AUTHORIZATION_PASS\n");

function metadata = collect_file_metadata(names,paths)
bytes = zeros(numel(paths),1);
modified = zeros(numel(paths),1);
for index = 1:numel(paths)
    information = dir(paths(index));
    assert(isscalar(information), ...
        "NMA:CVV4Phase3AuthorizationMetadataFailure", ...
        "Could not inspect a Phase-3 recovery authorization input.");
    bytes(index) = information.bytes;
    modified(index) = information.datenum;
end
metadata = table( ...
    names,paths,bytes,modified, ...
    VariableNames=["Name","Path","Bytes","Modified"]);
end

function validate_metadata(metadata,errorIdentifier)
for index = 1:height(metadata)
    information = dir(metadata.Path(index));
    assert(isscalar(information) && ...
        information.bytes == metadata.Bytes(index) && ...
        information.datenum == metadata.Modified(index), ...
        errorIdentifier, ...
        "A Phase-3 recovery authorization input changed: %s", ...
        metadata.Path(index));
end
end

function atomic_save(path,variableName,value)
partialFile = path+".partial";
payload = struct;
payload.(variableName) = value;
save(partialFile,"-struct","payload","-v7.3");
movefile(partialFile,path,"f");
end
