%% Run one locked v4 full-validation cell stage in a fresh MATLAB process.
addpath(fileparts(mfilename("fullpath")));
parallel.gpu.enableCUDAForwardCompatibility(true);

fold = str2double(getenv("ADNI_V4_CELL_FOLD"));
seed = str2double(getenv("ADNI_V4_CELL_SEED"));
action = string(getenv("ADNI_V4_CELL_ACTION"));
assert(isscalar(fold) && isfinite(fold) && ...
    fold == round(fold) && ismember(fold,1:5), ...
    "NMA:InvalidCVV4CellStageFold", ...
    "ADNI_V4_CELL_FOLD must be an integer from 1 through 5.");
assert(isscalar(seed) && isfinite(seed) && ...
    seed == round(seed) && ismember(seed,20260820:20260824), ...
    "NMA:InvalidCVV4CellStageSeed", ...
    "ADNI_V4_CELL_SEED is not a locked v4 seed.");
assert(ismember(action,["train-artifacts","finalize-validation"]), ...
    "NMA:InvalidCVV4CellStageAction", ...
    "ADNI_V4_CELL_ACTION must name a permitted fresh-process action.");

scriptDirectory = fileparts(mfilename("fullpath"));
projectRoot = fileparts(scriptDirectory);
cellRoot = fullfile( ...
    projectRoot,"adni_work","adni_3d_cv_v4", ...
    "locked_internal_validation_training", ...
    "fold_"+fold,"seed_"+seed);
result = adni_run_resnet3d18_cv_v4_validation_cell( ...
    fold,seed,Mode="full-validation",Action=action, ...
    OutputRoot=cellRoot,Verbose=true);
assert(result.Passed && result.OuterTestSealed && ...
    ~result.OuterTestPredictionsComputed && ...
    ~result.OuterTestEvaluated, ...
    "NMA:InvalidCVV4CellStageResult", ...
    "The fresh-process v4 cell stage returned an invalid result.");
fprintf( ...
    "ADNI_RESNET3D18_CV_V4_CELL_STAGE_PASS fold %d seed %d action %s\n", ...
    fold,seed,action);
