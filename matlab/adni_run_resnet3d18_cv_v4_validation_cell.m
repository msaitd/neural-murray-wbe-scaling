function validate_preflight(preflight)
assert(preflight.Passed && preflight.OuterTestSealed && ...
    ~preflight.TrainingPerformed && ...
    ~preflight.ValidationPredictionsComputed && ...
    ~preflight.OuterTestPredictionsComputed && ...
    ~preflight.OuterTestEvaluated && ...
    preflight.Phase1EngineeringSmokeAuthorized && ...
    ~preflight.GlobalADNITeacherReused && ...
    preflight.UniqueParticipants == 639 && ...
    preflight.UniqueVolumes == 1917, ...
    "NMA:InvalidCVV4CellPreflight", ...
    "The v4 Phase-0 preflight does not authorize sealed cell execution.");
for index = 1:height(preflight.InputMetadata)
    information = dir(preflight.InputMetadata.Path(index));
    assert(isscalar(information) && ...
        information.bytes == preflight.InputMetadata.Bytes(index) && ...
        information.datenum == preflight.InputMetadata.Modified(index), ...
        "NMA:ChangedCVV4PreflightInput", ...
        "A v4 Phase-0 input changed after preflight: %s", ...
        preflight.InputMetadata.Path(index));
end
end

