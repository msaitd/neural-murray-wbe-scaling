function cellResult = ...
    adni_run_resnet3d18_cv_v4_validation_cell(fold,seed,options)
%ADNI_RUN_RESNET3D18_CV_V4_VALIDATION_CELL Run one sealed v4 cell.
%
% The function performs fold-local training, training-only calibration,
% allocation, and validation evaluation. Outer-test prediction is absent by
% construction and belongs to a later atomic release program.

arguments
    fold (1,1) double {mustBeInteger,mustBeInRange(fold,1,5)}
    seed (1,1) double {mustBeInteger}
    options.Mode (1,1) string {mustBeMember(options.Mode, ...
        ["engineering-smoke","full-validation"])} = ...
        "engineering-smoke"
    options.Action (1,1) string {mustBeMember(options.Action, ...
        ["complete","train-artifacts","finalize-validation"])} = ...
        "complete"
    options.OutputRoot (1,1) string = ""
    options.Verbose (1,1) logical = true
end

lockedSeeds = (20260820:20260824).';
assert(ismember(seed,lockedSeeds), ...
    "NMA:InvalidCVV4Seed", ...
    "Seed %d is not one of the five locked v4 seeds.",seed);
mode = options.Mode;
action = options.Action;
assert(mode == "full-validation" || action == "complete", ...
    "NMA:InvalidCVV4SmokeAction", ...
    "The engineering smoke permits only the complete action.");
if mode == "engineering-smoke"
    assert(fold == 1 && seed == lockedSeeds(1), ...
        "NMA:InvalidCVV4SmokeCell", ...
        "The engineering smoke is locked to fold 1 seed 20260820.");
    teacherMaxEpochs = 1;
    studentMaxEpochs = 1;
    teacherValidationPatience = 1;
    studentValidationPatience = 1;
    calibrationMode = "stratified-training-baseline-12";
    expectedCalibrationImages = 12;
else
    teacherMaxEpochs = 8;
    studentMaxEpochs = 6;
    teacherValidationPatience = 3;
    studentValidationPatience = 3;
    calibrationMode = "all-training-visits";
    expectedCalibrationImages = NaN;
end

scriptDirectory = fileparts(mfilename("fullpath"));
projectRoot = fileparts(scriptDirectory);
workRoot = fullfile(projectRoot,"adni_work");
manifestFile = fullfile( ...
    workRoot,"adni_3d_cv_v2","fold_"+fold, ...
    "adni_3d_manifest.csv");
initializationFile = fullfile( ...
    workRoot,"adni_resnet3d18_imagenet_initialization.mat");
protocolFile = fullfile( ...
    projectRoot,"ADNI_NMA_CV_V4_LOCKED_INTERNAL_VALIDATION_PROTOCOL.md");
smokeProtocolFile = fullfile( ...
    projectRoot,"ADNI_NMA_CV_V4_ENGINEERING_SMOKE_PROTOCOL.md");
preflightFile = fullfile( ...
    workRoot,"adni_3d_cv_v4", ...
    "locked_internal_validation_preflight", ...
    "v4_locked_internal_validation_preflight.mat");
fullPreflightFile = fullfile( ...
    workRoot,"adni_3d_cv_v4","full_validation_preflight", ...
    "v4_full_validation_preflight.mat");
assert(isfile(manifestFile) && isfile(initializationFile) && ...
    isfile(protocolFile) && isfile(preflightFile) && ...
    (mode == "full-validation" || isfile(smokeProtocolFile)) && ...
    (mode == "engineering-smoke" || isfile(fullPreflightFile)), ...
    "NMA:MissingCVV4CellInput", ...
    "A locked v4 cell input is missing.");

preflightSource = load(preflightFile,"preflight");
preflight = preflightSource.preflight;
validate_preflight(preflight);
if mode == "full-validation"
    fullPreflightSource = load(fullPreflightFile,"preflight");
    fullPreflight = fullPreflightSource.preflight;
    validate_full_preflight(fullPreflight);
    fullPreflightStamp = file_stamp(fullPreflightFile);
else
    fullPreflightStamp = empty_stamp();
end
manifestStamp = file_stamp(manifestFile);
initializationStamp = file_stamp(initializationFile);
protocolStamp = file_stamp(protocolFile);
preflightStamp = file_stamp(preflightFile);
if mode == "engineering-smoke"
    smokeProtocolStamp = file_stamp(smokeProtocolFile);
else
    smokeProtocolStamp = empty_stamp();
end
assert(metadata_stamp_matches( ...
    preflight.InputMetadata,"fold_"+fold+"_manifest", ...
    manifestStamp) && ...
    metadata_stamp_matches( ...
    preflight.InputMetadata,"raw_imagenet_initialization", ...
    initializationStamp) && ...
    metadata_stamp_matches( ...
    preflight.InputMetadata,"locked_protocol",protocolStamp), ...
    "NMA:StaleCVV4CellPreflight", ...
    "The v4 Phase-0 preflight predates a locked cell input.");

manifest = readtable( ...
    manifestFile,Delimiter=",",TextType="string", ...
    VariableNamingRule="preserve");
splitContract = validate_manifest(manifest,fold);
if mode == "full-validation"
    expectedCalibrationImages = splitContract.NumTrainRows;
end

if strlength(options.OutputRoot) == 0
    if mode == "engineering-smoke"
        outputRoot = fullfile( ...
            workRoot,"adni_3d_cv_v4","engineering_smoke", ...
            "fold_"+fold,"seed_"+seed);
    else
        outputRoot = fullfile( ...
            workRoot,"adni_3d_cv_v4", ...
            "locked_internal_validation_training", ...
            "fold_"+fold,"seed_"+seed);
    end
else
    outputRoot = options.OutputRoot;
end
assert(startsWith( ...
    lower(string(outputRoot)),lower(string(workRoot)+filesep)), ...
    "NMA:InvalidCVV4OutputRoot", ...
    "The v4 output root must remain under adni_work.");
if ~isfolder(outputRoot)
    mkdir(outputRoot);
end

contract = struct;
contract.Version = "v4.0-locked-internal-validation";
contract.Mode = mode;
contract.Fold = fold;
contract.Seed = seed;
contract.HeadSeed = seed;
contract.TeacherSeed = seed+1;
contract.StudentSeed = seed;
contract.HeadMaxEpochs = 1;
contract.TeacherMaxEpochs = teacherMaxEpochs;
contract.StudentMaxEpochs = studentMaxEpochs;
contract.TeacherValidationPatience = teacherValidationPatience;
contract.StudentValidationPatience = studentValidationPatience;
contract.CalibrationMode = calibrationMode;
contract.ExpectedCalibrationImages = expectedCalibrationImages;
contract.ManifestStamp = manifestStamp;
contract.InitializationStamp = initializationStamp;
contract.ProtocolStamp = protocolStamp;
contract.SmokeProtocolStamp = smokeProtocolStamp;
contract.PreflightStamp = preflightStamp;
contract.FullValidationPreflightStamp = fullPreflightStamp;
contract.OutputRoot = outputRoot;
contract.OuterTestEvaluated = false;

headFile = fullfile(outputRoot,"dense_head_training.mat");
denseFile = fullfile(outputRoot,"dense_teacher_training.mat");
calibrationFile = fullfile(outputRoot,"training_calibration_allocation.mat");
proportionalFile = fullfile(outputRoot,"proportional_student_training.mat");
nmaFile = fullfile(outputRoot,"multi_resource_nma_student_training.mat");
resultFile = fullfile(outputRoot,"validation_cell_result.mat");
trainingReceiptFile = fullfile( ...
    outputRoot,"training_artifacts_complete.mat");
stageArtifactFiles = [ ...
    headFile;denseFile;calibrationFile;proportionalFile;nmaFile];

if action == "train-artifacts" && isfile(trainingReceiptFile)
    source = load(trainingReceiptFile,"trainingReceipt");
    trainingReceipt = source.trainingReceipt;
    validate_saved_training_receipt( ...
        trainingReceipt,contract,splitContract,stageArtifactFiles);
    cellResult = trainingReceipt;
    fprintf( ...
        "Loaded completed v4 training receipt fold %d seed %d.\n", ...
        fold,seed);
    return
end
if action == "finalize-validation" && isfile(resultFile)
    source = load(resultFile,"cellResult");
    cellResult = source.cellResult;
    validate_saved_cell_result( ...
        cellResult,contract,splitContract,stageArtifactFiles);
    fprintf( ...
        "Loaded completed v4 validation cell fold %d seed %d.\n", ...
        fold,seed);
    return
end
if action == "finalize-validation"
    assert(all(isfile(stageArtifactFiles)), ...
        "NMA:MissingCVV4TrainingArtifactForFinalization", ...
        ["Finalize-validation requires all five training artifacts; " ...
        "it may not train a missing stage."]);
end

[headArtifact,headReused] = load_or_train_head( ...
    headFile,initializationFile,manifestFile,contract, ...
    splitContract,options.Verbose);
[denseArtifact,denseReused] = load_or_train_dense( ...
    denseFile,headFile,headArtifact,manifestFile, ...
    contract,splitContract,options.Verbose);
[calibrationArtifact,calibrationReused] = ...
    load_or_create_calibration( ...
    calibrationFile,denseFile,denseArtifact,manifest, ...
    contract,splitContract,options.Verbose);
[proportionalArtifact,proportionalReused] = ...
    load_or_train_student( ...
    proportionalFile,"proportional",denseFile, ...
    calibrationFile,denseArtifact,calibrationArtifact, ...
    manifestFile,contract,splitContract,options.Verbose);
[nmaArtifact,nmaReused] = load_or_train_student( ...
    nmaFile,"multi-resource-NMA",denseFile, ...
    calibrationFile,denseArtifact,calibrationArtifact, ...
    manifestFile,contract,splitContract,options.Verbose);

stageArtifactStamps = repmat(empty_stamp(),5,1);
for artifactIndex = 1:numel(stageArtifactFiles)
    stageArtifactStamps(artifactIndex) = ...
        file_stamp(stageArtifactFiles(artifactIndex));
end
stageArtifactReused = [ ...
    headReused;denseReused;calibrationReused; ...
    proportionalReused;nmaReused];
if action == "train-artifacts"
    trainingReceipt = struct;
    trainingReceipt.Design = ...
        "v4 full-validation training-artifact completion receipt";
    trainingReceipt.Contract = contract;
    trainingReceipt.SplitContract = splitContract;
    trainingReceipt.StageArtifactFiles = stageArtifactFiles;
    trainingReceipt.StageArtifactStamps = stageArtifactStamps;
    trainingReceipt.StageArtifactReused = stageArtifactReused;
    trainingReceipt.CompletedStageArtifacts = 5;
    trainingReceipt.ValidationPredictionsComputed = false;
    trainingReceipt.OuterTestPredictionsComputed = false;
    trainingReceipt.OuterTestEvaluated = false;
    trainingReceipt.OuterTestSealed = true;
    trainingReceipt.Passed = true;
    trainingReceipt.CreatedAt = datetime("now",TimeZone="local");
    atomic_save( ...
        trainingReceiptFile,"trainingReceipt",trainingReceipt);
    cellResult = trainingReceipt;
    fprintf( ...
        "CV_V4_TRAINING_ARTIFACTS_PASS fold %d seed %d reused %d/5\n", ...
        fold,seed,sum(stageArtifactReused));
    return
end
if action == "finalize-validation"
    assert(all(stageArtifactReused), ...
        "NMA:CVV4FinalizationTrainedArtifact", ...
        "Finalize-validation unexpectedly trained a stage artifact.");
end

denseEvaluation = reproduce_validation( ...
    denseArtifact.Training.Network,manifestFile, ...
    denseArtifact.Training.BestValidation, ...
    splitContract.NumValidationSubjects);
proportionalEvaluation = reproduce_validation( ...
    proportionalArtifact.Training.Network,manifestFile, ...
    proportionalArtifact.Training.BestValidation, ...
    splitContract.NumValidationSubjects);
nmaEvaluation = reproduce_validation( ...
    nmaArtifact.Training.Network,manifestFile, ...
    nmaArtifact.Training.BestValidation, ...
    splitContract.NumValidationSubjects);

method = ["dense";"proportional";"multi-resource-NMA"];
evaluations = { ...
    denseEvaluation;proportionalEvaluation;nmaEvaluation};
widths = [ ...
    64 128 256 512; ...
    double(calibrationArtifact.ProportionalAllocation.TargetWidths(:)).'; ...
    double(calibrationArtifact.NMAAllocation.TargetWidths(:)).'];
validationSummary = repmat(empty_metric_row(),3,1);
for methodIndex = 1:3
    validationSummary(methodIndex) = metric_row( ...
        method(methodIndex),evaluations{methodIndex}, ...
        widths(methodIndex,:));
end
validationSummary = struct2table(validationSummary);
assert(all(isfinite(validationSummary{:,6:end}),"all"), ...
    "NMA:NonfiniteCVV4ValidationSummary", ...
    "A v4 validation-only cell metric is nonfinite.");

cellResult = struct;
cellResult.Design = ...
    "fold-local pretrained teacher and training-only multi-resource NMA";
cellResult.Contract = contract;
cellResult.SplitContract = splitContract;
cellResult.Methods = method;
cellResult.ValidationSummary = validationSummary;
cellResult.DenseValidation = denseEvaluation;
cellResult.ProportionalValidation = proportionalEvaluation;
cellResult.NMAValidation = nmaEvaluation;
cellResult.NMAAllocation = calibrationArtifact.NMAAllocation;
cellResult.ProportionalAllocation = ...
    calibrationArtifact.ProportionalAllocation;
cellResult.CalibrationRows = calibrationArtifact.CalibrationRows;
cellResult.StageArtifactFiles = stageArtifactFiles;
cellResult.StageArtifactStamps = stageArtifactStamps;
cellResult.StageArtifactReused = stageArtifactReused;
cellResult.AllStageArtifactsReused = all(stageArtifactReused);
cellResult.CompletedStageArtifacts = 5;
cellResult.TrainingOnlyCalibration = true;
cellResult.ValidationOnlyEvaluation = true;
cellResult.FullValidationCell = mode == "full-validation";
cellResult.PredictiveMetricsForInference = false;
cellResult.OuterTestPredictionsComputed = false;
cellResult.OuterTestEvaluated = false;
cellResult.OuterTestSealed = true;
cellResult.Passed = true;
cellResult.CreatedAt = datetime("now",TimeZone="local");
atomic_save(resultFile,"cellResult",cellResult);

disp(validationSummary);
fprintf( ...
    "CV_V4_CELL_PASS mode %s fold %d seed %d reused %d/5 NMA [%s]\n", ...
    mode,fold,seed,sum(stageArtifactReused), ...
    strjoin(string(cellResult.NMAAllocation.TargetWidths.')," "));
end

function validate_saved_training_receipt( ...
    receipt,contract,splitContract,stageArtifactFiles)
assert(receipt.Passed && isequaln(receipt.Contract,contract) && ...
    isequaln(receipt.SplitContract,splitContract) && ...
    isequal(receipt.StageArtifactFiles,stageArtifactFiles) && ...
    receipt.CompletedStageArtifacts == 5 && ...
    ~receipt.ValidationPredictionsComputed && ...
    ~receipt.OuterTestPredictionsComputed && ...
    ~receipt.OuterTestEvaluated && receipt.OuterTestSealed, ...
    "NMA:InvalidSavedCVV4TrainingReceipt", ...
    "A saved v4 training-artifact receipt is stale or invalid.");
for index = 1:numel(stageArtifactFiles)
    current = file_stamp(stageArtifactFiles(index));
    assert(stamp_matches(current,receipt.StageArtifactStamps(index)), ...
        "NMA:ChangedSavedCVV4TrainingArtifact", ...
        "A v4 stage artifact changed after its training receipt.");
end
end

function validate_saved_cell_result( ...
    cellResult,contract,splitContract,stageArtifactFiles)
assert(cellResult.Passed && cellResult.FullValidationCell && ...
    isequaln(cellResult.Contract,contract) && ...
    isequaln(cellResult.SplitContract,splitContract) && ...
    isequal(cellResult.StageArtifactFiles,stageArtifactFiles) && ...
    cellResult.CompletedStageArtifacts == 5 && ...
    cellResult.TrainingOnlyCalibration && ...
    cellResult.ValidationOnlyEvaluation && ...
    ~cellResult.PredictiveMetricsForInference && ...
    ~cellResult.OuterTestPredictionsComputed && ...
    ~cellResult.OuterTestEvaluated && cellResult.OuterTestSealed && ...
    height(cellResult.ValidationSummary) == 3, ...
    "NMA:InvalidSavedCVV4ValidationCell", ...
    "A saved v4 full-validation cell is stale or invalid.");
for index = 1:numel(stageArtifactFiles)
    current = file_stamp(stageArtifactFiles(index));
    assert(stamp_matches( ...
        current,cellResult.StageArtifactStamps(index)), ...
        "NMA:ChangedSavedCVV4StageArtifact", ...
        "A saved v4 stage artifact changed after cell completion.");
end
end

function contract = validate_manifest(manifest,fold)
required = [ ...
    "subject","imageDataId","group","classIndex", ...
    "split","visit","matPath"];
assert(all(ismember(required, ...
    string(manifest.Properties.VariableNames))) && ...
    all(isfile(manifest.matPath)), ...
    "NMA:InvalidCVV4CellManifest", ...
    "Fold %d manifest columns or files are invalid.",fold);
trainRows = manifest(manifest.split == "train",:);
validationRows = manifest(manifest.split == "validation",:);
testRows = manifest(manifest.split == "test",:);
trainSubjects = unique(trainRows.subject);
validationSubjects = unique(validationRows.subject);
testSubjects = unique(testRows.subject);
trainMultiplicity = groupcounts(categorical(trainRows.subject));
expectedTrainRows = [1146;1149;1152;1155;1149];
expectedTrainSubjects = [382;383;384;385;383];
expectedValidationSubjects = [128;128;127;127;129];
expectedTestSubjects = [129;128;128;127;127];
assert(height(trainRows) == expectedTrainRows(fold) && ...
    numel(trainSubjects) == expectedTrainSubjects(fold) && ...
    all(trainMultiplicity == 3) && ...
    height(validationRows) == ...
    expectedValidationSubjects(fold) && ...
    numel(validationSubjects) == ...
    expectedValidationSubjects(fold) && ...
    height(testRows) == expectedTestSubjects(fold) && ...
    numel(testSubjects) == expectedTestSubjects(fold) && ...
    all(validationRows.visit == "sc") && ...
    all(testRows.visit == "sc") && ...
    isempty(intersect(trainSubjects,validationSubjects)) && ...
    isempty(intersect(trainSubjects,testSubjects)) && ...
    isempty(intersect(validationSubjects,testSubjects)), ...
    "NMA:CVV4CellSplitContractViolation", ...
    "Fold %d violates participant or visit separation.",fold);
contract = struct;
contract.NumTrainRows = height(trainRows);
contract.NumTrainSubjects = numel(trainSubjects);
contract.NumValidationRows = height(validationRows);
contract.NumValidationSubjects = numel(validationSubjects);
contract.NumTestRows = height(testRows);
contract.NumTestSubjects = numel(testSubjects);
contract.OuterTestEvaluated = false;
end

function [artifact,reused] = load_or_train_head( ...
    artifactFile,initializationFile,manifestFile,contract, ...
    splitContract,verbose)
if isfile(artifactFile)
    source = load(artifactFile,"headArtifact");
    artifact = source.headArtifact;
    validate_head_artifact(artifact,contract,splitContract);
    reused = true;
    fprintf("Loaded v4 dense head fold %d seed %d.\n", ...
        contract.Fold,contract.Seed);
    return
end
initialization = load(initializationFile,"net","report");
[resetNetwork,resetReport] = ...
    adni_resnet3d18_reset_classifier( ...
    initialization.net,contract.HeadSeed);
[headNetwork,headScope] = ...
    adni_resnet3d18_set_training_scope( ...
    resetNetwork,"head-only",HeadFactor=1);
training = adni_train_resnet3d18( ...
    fileparts(manifestFile),Network=headNetwork, ...
    MaxEpochs=contract.HeadMaxEpochs,MiniBatchSize=1, ...
    InitialLearnRate=1e-3,L2Regularization=1e-4, ...
    ExecutionEnvironment="gpu", ...
    EnableCUDAForwardCompatibility=true, ...
    DeterministicGPU=true,ValidationPatience=1, ...
    BatchNormalizationStatistics="moving", ...
    ResetInputNormalization=true,UseAugmentation=true, ...
    RandomSeed=contract.HeadSeed,SaveFile="",Verbose=verbose);
artifact = struct;
artifact.Type = "dense-head-training";
artifact.Contract = contract;
artifact.InitializationReport = initialization.report;
artifact.ClassifierReset = resetReport;
artifact.HeadScope = headScope;
artifact.Training = training;
artifact.OuterTestEvaluated = false;
artifact.Passed = true;
artifact.CreatedAt = datetime("now",TimeZone="local");
validate_head_artifact(artifact,contract,splitContract);
atomic_save(artifactFile,"headArtifact",artifact);
reused = false;
end

function validate_head_artifact(artifact,contract,splitContract)
training = artifact.Training;
assert(artifact.Type == "dense-head-training" && ...
    isequaln(artifact.Contract,contract) && ...
    artifact.Passed && ~artifact.OuterTestEvaluated && ...
    artifact.ClassifierReset.RandomSeed == contract.HeadSeed && ...
    artifact.ClassifierReset.BackboneExact && ...
    artifact.HeadScope.Scope == "head-only" && ...
    artifact.HeadScope.NumFrozenTensors > 0 && ...
    ~training.TestEvaluated && ...
    isequal(training.Widths,[64;128;256;512]) && ...
    training.TrainRows == splitContract.NumTrainRows && ...
    training.TrainSubjects == splitContract.NumTrainSubjects && ...
    training.ValidationRows == splitContract.NumValidationRows && ...
    training.ValidationSubjects == ...
    splitContract.NumValidationSubjects && ...
    training.Options.MaxEpochs == 1 && ...
    training.Options.MiniBatchSize == 1 && ...
    training.Options.InitialLearnRate == 1e-3 && ...
    training.Options.L2Regularization == 1e-4 && ...
    training.Options.ExecutionEnvironment == "gpu" && ...
    training.Options.DeterministicGPU && ...
    training.Options.ValidationPatience == 1 && ...
    training.Options.BatchNormalizationStatistics == "moving" && ...
    training.Options.ResetInputNormalization && ...
    training.Options.UseAugmentation && ...
    training.Options.RandomSeed == contract.HeadSeed && ...
    network_is_finite(training.Network), ...
    "NMA:InvalidCVV4HeadArtifact", ...
    "The v4 dense-head artifact is stale or invalid.");
end

function [artifact,reused] = load_or_train_dense( ...
    artifactFile,headFile,headArtifact,manifestFile, ...
    contract,splitContract,verbose)
headStamp = file_stamp(headFile);
if isfile(artifactFile)
    source = load(artifactFile,"denseArtifact");
    artifact = source.denseArtifact;
    validate_dense_artifact( ...
        artifact,contract,splitContract,headStamp);
    reused = true;
    fprintf("Loaded v4 dense teacher fold %d seed %d.\n", ...
        contract.Fold,contract.Seed);
    return
end
[fullNetwork,fullScope] = ...
    adni_resnet3d18_set_training_scope( ...
    headArtifact.Training.Network,"all", ...
    HeadFactor=1,BackboneFactor=1);
training = adni_train_resnet3d18_distillation( ...
    fileparts(manifestFile),fullNetwork,fullNetwork, ...
    MaxEpochs=contract.TeacherMaxEpochs, ...
    InitialLearnRate=2e-5,MinimumLearnRateRatio=0, ...
    Alpha=1,Temperature=4,L2Regularization=1e-4, ...
    GradientThreshold=5,GradientAccumulationSteps=1, ...
    ValidationPatience=contract.TeacherValidationPatience, ...
    UseAugmentation=true,TrainingSampling="all-visits", ...
    RandomSeed=contract.TeacherSeed, ...
    EnableCUDAForwardCompatibility=true, ...
    DeterministicGPU=true,BatchNormalizationMode="update", ...
    SaveFile="",Verbose=verbose);
artifact = struct;
artifact.Type = "dense-teacher-training";
artifact.Contract = contract;
artifact.HeadArtifactStamp = headStamp;
artifact.FullScope = fullScope;
artifact.Training = training;
artifact.OuterTestEvaluated = false;
artifact.Passed = true;
artifact.CreatedAt = datetime("now",TimeZone="local");
validate_dense_artifact( ...
    artifact,contract,splitContract,headStamp);
atomic_save(artifactFile,"denseArtifact",artifact);
reused = false;
end

function validate_dense_artifact( ...
    artifact,contract,splitContract,headStamp)
training = artifact.Training;
assert(artifact.Type == "dense-teacher-training" && ...
    isequaln(artifact.Contract,contract) && ...
    stamp_matches(artifact.HeadArtifactStamp,headStamp) && ...
    artifact.Passed && ~artifact.OuterTestEvaluated && ...
    artifact.FullScope.Scope == "all" && ...
    artifact.FullScope.NumFrozenTensors == 0 && ...
    ~training.TestEvaluated && ...
    isequal(training.StudentWidths,[64;128;256;512]) && ...
    isequal(training.TeacherWidths,[64;128;256;512]) && ...
    training.Options.MaxEpochs == contract.TeacherMaxEpochs && ...
    training.Options.InitialLearnRate == 2e-5 && ...
    training.Options.MinimumLearnRateRatio == 0 && ...
    training.Options.Alpha == 1 && ...
    training.Options.Temperature == 4 && ...
    training.Options.L2Regularization == 1e-4 && ...
    training.Options.GradientThreshold == 5 && ...
    training.Options.GradientAccumulationSteps == 1 && ...
    training.Options.ValidationPatience == ...
    contract.TeacherValidationPatience && ...
    training.Options.UseAugmentation && ...
    training.Options.TrainingSampling == "all-visits" && ...
    training.Options.RandomSeed == contract.TeacherSeed && ...
    training.Options.DeterministicGPU && ...
    training.Options.BatchNormalizationMode == "update" && ...
    training.NumTrainRows == splitContract.NumTrainRows && ...
    training.NumTrainSubjects == splitContract.NumTrainSubjects && ...
    training.NumValidationRows == splitContract.NumValidationRows && ...
    training.NumValidationSubjects == ...
    splitContract.NumValidationSubjects && ...
    training.NumOptimizationSamplesPerEpoch == ...
    splitContract.NumTrainRows && ...
    training.BestValidation.Split == "validation" && ...
    training.BestValidation.NumSubjects == ...
    splitContract.NumValidationSubjects && ...
    height(training.History) >= 1 && ...
    height(training.History) <= contract.TeacherMaxEpochs && ...
    all(isfinite(training.History{:,2:6}),"all") && ...
    all(isfinite( ...
    training.OptimizerDiagnostics.TrainableGradientNorm)) && ...
    network_is_finite(training.Network), ...
    "NMA:InvalidCVV4DenseArtifact", ...
    "The v4 dense-teacher artifact is stale or invalid.");
end

function [artifact,reused] = load_or_create_calibration( ...
    artifactFile,denseFile,denseArtifact,manifest, ...
    contract,splitContract,verbose)
denseStamp = file_stamp(denseFile);
if isfile(artifactFile)
    source = load(artifactFile,"calibrationArtifact");
    artifact = source.calibrationArtifact;
    validate_calibration_artifact( ...
        artifact,contract,splitContract,denseStamp,manifest);
    reused = true;
    fprintf("Loaded v4 training calibration fold %d seed %d.\n", ...
        contract.Fold,contract.Seed);
    return
end
trainRows = manifest(manifest.split == "train",:);
classNames = ["AD";"CN";"MCI"];
classCounts = zeros(3,1);
for classIndex = 1:3
    classCounts(classIndex) = ...
        sum(trainRows.group == classNames(classIndex));
end
classWeights = sum(classCounts)./(3*classCounts);
classWeights = classWeights/mean(classWeights);
if contract.CalibrationMode == "all-training-visits"
    calibrationRows = trainRows;
    progressFrequency = 25;
else
    baselineRows = sortrows( ...
        trainRows(trainRows.visit == "sc",:), ...
        ["group","subject","imageDataId"]);
    selectedIndices = zeros(12,1);
    nextIndex = 0;
    for classIndex = 1:3
        candidates = find( ...
            baselineRows.group == classNames(classIndex));
        assert(numel(candidates) >= 4, ...
            "NMA:InsufficientCVV4SmokeCalibrationClass", ...
            "The smoke requires four training baselines per class.");
        selectedIndices(nextIndex+(1:4)) = candidates(1:4);
        nextIndex = nextIndex+4;
    end
    calibrationRows = baselineRows(selectedIndices,:);
    progressFrequency = 4;
end
assert(height(calibrationRows) == ...
    contract.ExpectedCalibrationImages && ...
    all(ismember(calibrationRows.imageDataId,trainRows.imageDataId)) && ...
    isempty(intersect(unique(calibrationRows.subject), ...
    unique(manifest.subject(manifest.split ~= "train")))), ...
    "NMA:CVV4CalibrationLeakage", ...
    "The v4 calibration rows are not training-only.");

previousDeterminism = deep.gpu.deterministicAlgorithms(true);
previousGPUGenerator = gpurng;
determinismCleanup = onCleanup(@() restore_gpu_state( ...
    previousDeterminism,previousGPUGenerator));
gpurng(contract.Seed+2,"Threefry");
calibration = nma_resnet3d18_calibrate( ...
    denseArtifact.Training.Network, ...
    calibrationRows.matPath,calibrationRows.classIndex, ...
    MiniBatchSize=1,MaxBatches=Inf,UseGPU=true, ...
    ClassWeights=classWeights,Verbose=verbose, ...
    ProgressFrequency=progressFrequency);
clear determinismCleanup
restore_gpu_state(previousDeterminism,previousGPUGenerator);

denseParameters = nma_resnet3d18_resource( ...
    [64;128;256;512],Resource="parameters",NumClasses=3);
denseMACs = nma_resnet3d18_resource( ...
    [64;128;256;512],Resource="macs",NumClasses=3);
parameterCeiling = 24923027;
macCeiling = 9865390056;
budgetFractions = [ ...
    parameterCeiling/denseParameters,macCeiling/denseMACs];
nmaAllocation = nma_resnet3d18_allocate_multiresource( ...
    calibration,Resources=["parameters","macs"], ...
    BudgetFractions=budgetFractions, ...
    Estimator="multiplicative",NumClasses=3,P=2, ...
    Granularity=[4 8 8 8],MinWidth=[32 64 128 256], ...
    MaxWidth=[64 128 256 512]);
proportionalAllocation = fixed_allocation( ...
    calibration,[52;120;224;440], ...
    ["parameters";"macs"],budgetFractions(:));

artifact = struct;
artifact.Type = "training-calibration-allocation";
artifact.Contract = contract;
artifact.DenseArtifactStamp = denseStamp;
artifact.CalibrationRows = calibrationRows(:,[ ...
    "subject","imageDataId","group","classIndex", ...
    "visit","matPath"]);
artifact.ClassCounts = classCounts;
artifact.ClassWeights = classWeights;
artifact.Calibration = calibration;
artifact.NMAAllocation = nmaAllocation;
artifact.ProportionalAllocation = proportionalAllocation;
artifact.ParameterCeiling = parameterCeiling;
artifact.MACCeiling = macCeiling;
artifact.TrainingOnly = true;
artifact.ValidationDataUsed = false;
artifact.OuterTestEvaluated = false;
artifact.Passed = true;
artifact.CreatedAt = datetime("now",TimeZone="local");
validate_calibration_artifact( ...
    artifact,contract,splitContract,denseStamp,manifest);
atomic_save(artifactFile,"calibrationArtifact",artifact);
reused = false;
end

function validate_calibration_artifact( ...
    artifact,contract,splitContract,denseStamp,manifest)
trainingRows = manifest(manifest.split == "train",:);
evaluationSubjects = unique( ...
    manifest.subject(manifest.split ~= "train"));
nmaResources = artifact.NMAAllocation.ResourceTable;
assert(artifact.Type == "training-calibration-allocation" && ...
    isequaln(artifact.Contract,contract) && ...
    stamp_matches(artifact.DenseArtifactStamp,denseStamp) && ...
    artifact.Passed && artifact.TrainingOnly && ...
    ~artifact.ValidationDataUsed && ...
    ~artifact.OuterTestEvaluated && ...
    height(artifact.CalibrationRows) == ...
    contract.ExpectedCalibrationImages && ...
    artifact.Calibration.NumImages == ...
    contract.ExpectedCalibrationImages && ...
    artifact.Calibration.NumBatches == ...
    contract.ExpectedCalibrationImages && ...
    artifact.Calibration.MiniBatchSize == 1 && ...
    artifact.Calibration.UseGPU && ...
    isequal(artifact.Calibration.Spec.BaselineWidths, ...
    [64;128;256;512]) && ...
    all(isfinite(artifact.Calibration.Losses)) && ...
    all(isfinite( ...
    artifact.Calibration.StageDemand.MultiplicativeMeanAbs)) && ...
    all(ismember(artifact.CalibrationRows.imageDataId, ...
    trainingRows.imageDataId)) && ...
    isempty(intersect(unique(artifact.CalibrationRows.subject), ...
    evaluationSubjects)) && ...
    numel(unique(trainingRows.subject)) == ...
    splitContract.NumTrainSubjects && ...
    artifact.ParameterCeiling == 24923027 && ...
    artifact.MACCeiling == 9865390056 && ...
    artifact.NMAAllocation.Estimator == "multiplicative" && ...
    artifact.NMAAllocation.P == 2 && ...
    isequal(artifact.NMAAllocation.Resources, ...
    ["parameters";"macs"]) && ...
    all(mod(artifact.NMAAllocation.TargetWidths, ...
    [4;8;8;8]) == 0) && ...
    all(artifact.NMAAllocation.TargetWidths >= ...
    [32;64;128;256]) && ...
    all(artifact.NMAAllocation.TargetWidths <= ...
    [64;128;256;512]) && ...
    all(nmaResources.Projected <= ...
    nmaResources.Budget*(1+1e-12)) && ...
    isequal(artifact.ProportionalAllocation.TargetWidths, ...
    [52;120;224;440]) && ...
    all(artifact.ProportionalAllocation.ProjectedResources <= ...
    artifact.ProportionalAllocation.Budgets*(1+1e-12)), ...
    "NMA:InvalidCVV4CalibrationArtifact", ...
    "The v4 training calibration/allocation artifact is stale or invalid.");
for probeIndex = 1:height(artifact.Calibration.Probes)
    assert(all(isfinite(artifact.Calibration.Probes. ...
        ForwardByChannel{probeIndex})) && ...
        all(isfinite(artifact.Calibration.Probes. ...
        BackwardByChannel{probeIndex})) && ...
        all(isfinite(artifact.Calibration.Probes. ...
        MultiplicativeByChannel{probeIndex})), ...
        "NMA:NonfiniteCVV4CalibrationChannel", ...
        "A v4 calibration channel demand is nonfinite.");
end
end

function allocation = fixed_allocation( ...
    calibration,widths,resources,budgetFractions)
baselineWidths = double(calibration.Spec.BaselineWidths(:));
widths = double(widths(:));
baseline = zeros(numel(resources),1);
projected = zeros(numel(resources),1);
for resourceIndex = 1:numel(resources)
    baseline(resourceIndex) = nma_resnet3d18_resource( ...
        baselineWidths,Resource=resources(resourceIndex), ...
        NumClasses=3);
    projected(resourceIndex) = nma_resnet3d18_resource( ...
        widths,Resource=resources(resourceIndex),NumClasses=3);
end
budgets = budgetFractions(:).*baseline;
assert(all(projected <= budgets*(1+1e-12)), ...
    "NMA:CVV4ProportionalBudgetViolation", ...
    "The fixed proportional control exceeds a resource ceiling.");
allocation = struct;
allocation.Model = calibration.Spec.Model;
allocation.Resource = "multiple";
allocation.Resources = resources(:);
allocation.Estimator = "multiplicative";
allocation.Control = "fixed-proportional-width";
allocation.NumClasses = 3;
allocation.P = 2;
allocation.BaselineWidths = baselineWidths;
allocation.TargetWidths = widths;
allocation.BaselineResources = baseline;
allocation.BudgetFractions = budgetFractions(:);
allocation.Budgets = budgets;
allocation.ProjectedResources = projected;
allocation.ResourceFractions = projected./baseline;
allocation.CreatedAt = datetime("now",TimeZone="local");
end

function [artifact,reused] = load_or_train_student( ...
    artifactFile,method,denseFile,calibrationFile, ...
    denseArtifact,calibrationArtifact,manifestFile, ...
    contract,splitContract,verbose)
denseStamp = file_stamp(denseFile);
calibrationStamp = file_stamp(calibrationFile);
if method == "proportional"
    allocation = calibrationArtifact.ProportionalAllocation;
else
    allocation = calibrationArtifact.NMAAllocation;
end
if isfile(artifactFile)
    variableName = method_variable_name(method);
    source = load(artifactFile,variableName);
    artifact = source.(variableName);
    validate_student_artifact( ...
        artifact,method,allocation,contract,splitContract, ...
        denseStamp,calibrationStamp);
    reused = true;
    fprintf("Loaded v4 %s fold %d seed %d.\n", ...
        method,contract.Fold,contract.Seed);
    return
end
rng(contract.StudentSeed,"twister");
[studentNetwork,surgery] = nma_resnet3d18_rebuild( ...
    denseArtifact.Training.Network,allocation, ...
    calibrationArtifact.Calibration);
training = adni_train_resnet3d18_distillation( ...
    fileparts(manifestFile),studentNetwork, ...
    denseArtifact.Training.Network, ...
    MaxEpochs=contract.StudentMaxEpochs, ...
    InitialLearnRate=2e-5,MinimumLearnRateRatio=0.1, ...
    Alpha=0.9,Temperature=2,L2Regularization=1e-4, ...
    GradientThreshold=5,GradientAccumulationSteps=1, ...
    ValidationPatience=contract.StudentValidationPatience, ...
    UseAugmentation=true, ...
    TrainingSampling="one-visit-per-subject", ...
    RandomSeed=contract.StudentSeed, ...
    EnableCUDAForwardCompatibility=true, ...
    DeterministicGPU=true,BatchNormalizationMode="update", ...
    SaveFile="",Verbose=verbose);
artifact = struct;
artifact.Type = "compressed-student-training";
artifact.Method = method;
artifact.Contract = contract;
artifact.DenseArtifactStamp = denseStamp;
artifact.CalibrationArtifactStamp = calibrationStamp;
artifact.Allocation = allocation;
artifact.Surgery = surgery;
artifact.Training = training;
artifact.OuterTestEvaluated = false;
artifact.Passed = true;
artifact.CreatedAt = datetime("now",TimeZone="local");
validate_student_artifact( ...
    artifact,method,allocation,contract,splitContract, ...
    denseStamp,calibrationStamp);
variableName = method_variable_name(method);
atomic_save(artifactFile,variableName,artifact);
reused = false;
end

function validate_student_artifact( ...
    artifact,method,allocation,contract,splitContract, ...
    denseStamp,calibrationStamp)
training = artifact.Training;
actualParameters = sum(cellfun( ...
    @numel,training.Network.Learnables.Value));
analyticalParameters = nma_resnet3d18_resource( ...
    allocation.TargetWidths,Resource="parameters",NumClasses=3);
analyticalMACs = nma_resnet3d18_resource( ...
    allocation.TargetWidths,Resource="macs",NumClasses=3);
assert(artifact.Type == "compressed-student-training" && ...
    artifact.Method == method && ...
    isequaln(artifact.Contract,contract) && ...
    stamp_matches(artifact.DenseArtifactStamp,denseStamp) && ...
    stamp_matches(artifact.CalibrationArtifactStamp, ...
    calibrationStamp) && ...
    artifact.Passed && ~artifact.OuterTestEvaluated && ...
    isequal(double(artifact.Allocation.TargetWidths(:)), ...
    double(allocation.TargetWidths(:))) && ...
    ~training.TestEvaluated && ...
    isequal(double(training.StudentWidths(:)), ...
    double(allocation.TargetWidths(:))) && ...
    isequal(training.TeacherWidths,[64;128;256;512]) && ...
    training.Options.MaxEpochs == contract.StudentMaxEpochs && ...
    training.Options.InitialLearnRate == 2e-5 && ...
    training.Options.MinimumLearnRateRatio == 0.1 && ...
    training.Options.Alpha == 0.9 && ...
    training.Options.Temperature == 2 && ...
    training.Options.L2Regularization == 1e-4 && ...
    training.Options.GradientThreshold == 5 && ...
    training.Options.GradientAccumulationSteps == 1 && ...
    training.Options.ValidationPatience == ...
    contract.StudentValidationPatience && ...
    training.Options.UseAugmentation && ...
    training.Options.TrainingSampling == ...
    "one-visit-per-subject" && ...
    training.Options.RandomSeed == contract.StudentSeed && ...
    training.Options.DeterministicGPU && ...
    training.Options.BatchNormalizationMode == "update" && ...
    training.NumTrainRows == splitContract.NumTrainRows && ...
    training.NumTrainSubjects == splitContract.NumTrainSubjects && ...
    training.NumValidationRows == splitContract.NumValidationRows && ...
    training.NumValidationSubjects == ...
    splitContract.NumValidationSubjects && ...
    training.NumOptimizationSamplesPerEpoch == ...
    splitContract.NumTrainSubjects && ...
    training.BestValidation.Split == "validation" && ...
    training.BestValidation.NumSubjects == ...
    splitContract.NumValidationSubjects && ...
    height(training.History) >= 1 && ...
    height(training.History) <= contract.StudentMaxEpochs && ...
    all(isfinite(training.History{:,2:6}),"all") && ...
    all(isfinite( ...
    training.OptimizerDiagnostics.TrainableGradientNorm)) && ...
    actualParameters == analyticalParameters && ...
    actualParameters == ...
    artifact.Surgery.CompressedLearnableParameters && ...
    analyticalMACs == artifact.Surgery.CompressedMACs && ...
    network_is_finite(training.Network), ...
    "NMA:InvalidCVV4StudentArtifact", ...
    "The v4 %s artifact is stale or invalid.",method);
end

function evaluation = reproduce_validation( ...
    network,manifestFile,stored,numExpectedSubjects)
assert(stored.Split == "validation" && ...
    stored.NumSubjects == numExpectedSubjects, ...
    "NMA:InvalidCVV4StoredValidation", ...
    "A stored v4 evaluation is not validation-only.");
evaluation = adni_evaluate_resnet3d18( ...
    network,manifestFile,Split="validation", ...
    ExecutionEnvironment="gpu",BootstrapReplicates=0);
oldRows = stored.SubjectPredictions;
newRows = evaluation.SubjectPredictions;
assert(isequal(newRows.Subject,oldRows.Subject) && ...
    isequal(newRows.TrueGroup,oldRows.TrueGroup) && ...
    isequal(newRows.PredictedGroup,oldRows.PredictedGroup) && ...
    max(abs(newRows{:,{'ScoreAD','ScoreCN','ScoreMCI'}}- ...
    oldRows{:,{'ScoreAD','ScoreCN','ScoreMCI'}}),[],"all") <= 1e-5 && ...
    abs(evaluation.BalancedAccuracy-stored.BalancedAccuracy) <= 1e-12 && ...
    abs(evaluation.MacroF1-stored.MacroF1) <= 1e-12 && ...
    abs(evaluation.Accuracy-stored.Accuracy) <= 1e-12, ...
    "NMA:CVV4ValidationReproductionMismatch", ...
    "A saved v4 network does not reproduce validation.");
end

