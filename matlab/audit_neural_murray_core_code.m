%AUDIT_NEURAL_MURRAY_CORE_CODE Read-only static and numerical consistency audit.

root = fileparts(fileparts(mfilename("fullpath")));
matlabRoot = fullfile(root,"matlab");
addpath(matlabRoot);

files = [ ...
    "nma_probe_demand.m"; ...
    "nma_resnet3d18_calibrate.m"; ...
    "nma_resnet3d18_allocate_multiresource.m"; ...
    "nma_resnet3d18_resource.m"; ...
    "nma_resnet3d18_rebuild.m"; ...
    "adni_extract_3d.m"; ...
    "adni_run_resnet3d18_cv_v4_validation_cell.m"; ...
    "adni_resnet3d18_cv_v4_metrics.m"; ...
    "run_adni_resnet3d18_cv_v4_atomic_outer_test.m"; ...
    "analyze_adni_resnet3d18_cv_v4_outer_test.m"; ...
    "run_adni_resnet3d18_cv_v4_benchmark_cell.m"; ...
    "aggregate_adni_resnet3d18_cv_v4_paired_rtx5070.m"];

messageCount = 0;
for fileIndex = 1:numel(files)
    path = fullfile(matlabRoot,files(fileIndex));
    assert(isfile(path),"NMA:MissingAuditCodeFile", ...
        "Missing core file: %s",path);
    issues = checkcode(path,"-id");
    if ~isempty(issues)
        fprintf("CHECKCODE %s\n",path);
        for issueIndex = 1:numel(issues)
            fprintf("  L%d C%d %s %s\n", ...
                issues(issueIndex).line,issues(issueIndex).column, ...
                issues(issueIndex).id,issues(issueIndex).message);
        end
        messageCount = messageCount+numel(issues);
    end
end

dense = [64 128 256 512];
proportional = [52 120 224 440];
assert(nma_resnet3d18_resource(dense,Resource="parameters", ...
    NumClasses=3) == 33166339);
assert(nma_resnet3d18_resource(dense,Resource="macs", ...
    NumClasses=3) == 13249807872);
assert(nma_resnet3d18_resource(dense,Resource="activation", ...
    NumClasses=3) == 5875200);
assert(nma_resnet3d18_resource(proportional,Resource="parameters", ...
    NumClasses=3) == 24923027);
assert(nma_resnet3d18_resource(proportional,Resource="macs", ...
    NumClasses=3) == 9865390056);
assert(nma_resnet3d18_resource(proportional,Resource="activation", ...
    NumClasses=3) == 4932360);

fprintf("CORE_CODE_AUDIT files=%d checkcode_messages=%d resource_assertions=6 status=PASS\n", ...
    numel(files),messageCount);
