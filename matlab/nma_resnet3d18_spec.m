function spec = nma_resnet3d18_spec(net)
%NMA_RESNET3D18_SPEC Validate the MATLAB 3-D ResNet-18 graph contract.

arguments
    net (1,1) dlnetwork
end

spec = struct;
spec.Model = "adni-resnet3d18";
spec.InputName = "input";
spec.OutputName = "softmax";
spec.InputSize = [96 96 96 1];
spec.StageNumbers = (1:4).';
spec.StageNames = ["stack1";"stack2";"stack3";"stack4"];
spec.DemandProbeNames = [ ...
    "stack1:block2:relu2"; ...
    "stack2:block2:relu2"; ...
    "stack3:block2:relu2"; ...
    "stack4:block2:relu2"];
spec.HiddenProbeNames = [ ...
    "stack1:block1:relu1"; ...
    "stack1:block2:relu1"; ...
    "stack2:block1:relu1"; ...
    "stack2:block2:relu1"; ...
    "stack3:block1:relu1"; ...
    "stack3:block2:relu1"; ...
    "stack4:block1:relu1"; ...
    "stack4:block2:relu1"];
spec.AllProbeNames = [spec.DemandProbeNames;spec.HiddenProbeNames];
spec.SpatialSizes = [24;12;6;3];
spec.ActivationMultiplicity = [5;5;5;5];

layerNames = string({net.Layers.Name}).';
requiredLayers = [ ...
    spec.InputName;"conv1";"bn1"; ...
    spec.AllProbeNames; ...
    "stack1:block1:conv1";"stack1:block1:conv2"; ...
    "stack1:block2:conv1";"stack1:block2:conv2"; ...
    "stack2:block1:conv1";"stack2:block1:conv2"; ...
    "stack2:block1:skip_conv"; ...
    "stack2:block2:conv1";"stack2:block2:conv2"; ...
    "stack3:block1:conv1";"stack3:block1:conv2"; ...
    "stack3:block1:skip_conv"; ...
    "stack3:block2:conv1";"stack3:block2:conv2"; ...
    "stack4:block1:conv1";"stack4:block1:conv2"; ...
    "stack4:block1:skip_conv"; ...
    "stack4:block2:conv1";"stack4:block2:conv2"; ...
    "fc";spec.OutputName];
missing = setdiff(requiredLayers,layerNames);
assert(isempty(missing),"NMA:Unsupported3DResNet18Graph", ...
    "The network is not the expected MATLAB 3-D ResNet-18 graph. Missing: %s", ...
    strjoin(missing,", "));
assert(net.Initialized,"NMA:UninitializedNetwork", ...
    "The 3-D ResNet-18 network must be initialized.");
assert(any(string(net.InputNames) == spec.InputName), ...
    "NMA:UnexpectedInput","Expected network input '%s'.",spec.InputName);
assert(any(string(net.OutputNames) == spec.OutputName), ...
    "NMA:UnexpectedOutput","Expected network output '%s'.",spec.OutputName);

inputLayer = getLayer(net,spec.InputName);
assert(isequal(inputLayer.InputSize,spec.InputSize), ...
    "NMA:Unexpected3DInputSize", ...
    "Expected 3-D input size [%s].",strjoin(string(spec.InputSize)," "));
spec.BaselineWidths = [ ...
    getLayer(net,"stack1:block2:conv2").NumFilters; ...
    getLayer(net,"stack2:block2:conv2").NumFilters; ...
    getLayer(net,"stack3:block2:conv2").NumFilters; ...
    getLayer(net,"stack4:block2:conv2").NumFilters];

for stageIndex = 1:4
    probe = getLayer(net,spec.DemandProbeNames(stageIndex));
    assert(contains(class(probe),"ReLULayer"), ...
        "NMA:UnexpectedProbeType", ...
        "Demand probe %s is not a ReLU output.", ...
        spec.DemandProbeNames(stageIndex));
end

spec.ActivationCostPerChannel = ...
    spec.ActivationMultiplicity .* spec.SpatialSizes.^3;
spec.DefaultMinWidths = max(8,0.5*spec.BaselineWidths);
spec.DefaultMaxWidths = spec.BaselineWidths;
spec.DefaultGranularity = 8*ones(4,1);
end
