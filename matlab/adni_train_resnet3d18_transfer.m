function transfer = ...
    adni_train_resnet3d18_transfer(datasetRoot,options)
%ADNI_TRAIN_RESNET3D18_TRANSFER Two-stage ImageNet-inflated fine-tuning.
%
% Stage 1 adapts the new three-class head while the transferred backbone is
% frozen. Stage 2 unfreezes the complete network and fine-tunes at a lower
% learning rate. Validation data select each stage; test data are not
% evaluated here.

arguments
    datasetRoot (1,1) string
    options.Network = []
    options.InitializationReport (1,1) struct = struct
    options.InternalNormalization (1,1) string = "batch"
    options.HeadEpochs (1,1) double ...
        {mustBeInteger,mustBePositive} = 2
    options.FineTuneEpochs (1,1) double ...
        {mustBeInteger,mustBePositive} = 10
    options.HeadLearnRate (1,1) double {mustBePositive} = 1e-3
    options.FineTuneLearnRate (1,1) double {mustBePositive} = 2e-5
    options.L2Regularization (1,1) double {mustBeNonnegative} = 1e-4
    options.UseAugmentation (1,1) logical = true
    options.RandomSeed (1,1) double {mustBeInteger} = 20260727
    options.EnableCUDAForwardCompatibility (1,1) logical = true
    options.SaveFile (1,1) string = ""
    options.Verbose (1,1) logical = true
end

if isempty(options.Network)
    [initialNet,initializationReport] = ...
        adni_resnet3d18_initialize_imagenet( ...
        InternalNormalization=options.InternalNormalization);
else
    assert(isa(options.Network,"dlnetwork") && ...
        isscalar(options.Network), ...
        "NMA:InvalidTransferNetwork", ...
        "Network must be a scalar dlnetwork.");
    initialNet = options.Network;
    if isempty(fieldnames(options.InitializationReport))
        initializationReport = struct( ...
            "Method","provided-network", ...
            "CreatedAt",datetime("now",TimeZone="local"));
    else
        initializationReport = options.InitializationReport;
    end
end

[headNet,headScope] = adni_resnet3d18_set_training_scope( ...
    initialNet,"head-only",HeadFactor=1);
headTraining = adni_train_resnet3d18( ...
    datasetRoot,Network=headNet, ...
    MaxEpochs=options.HeadEpochs, ...
    MiniBatchSize=1, ...
    InitialLearnRate=options.HeadLearnRate, ...
    L2Regularization=options.L2Regularization, ...
    ExecutionEnvironment="gpu", ...
    EnableCUDAForwardCompatibility= ...
        options.EnableCUDAForwardCompatibility, ...
    ValidationPatience=max(1,options.HeadEpochs), ...
    BatchNormalizationStatistics="moving", ...
    ResetInputNormalization=true, ...
    UseAugmentation=options.UseAugmentation, ...
    RandomSeed=options.RandomSeed, ...
    Verbose=options.Verbose);

[fineTuneNet,fineTuneScope] = ...
    adni_resnet3d18_set_training_scope( ...
    headTraining.Network,"all", ...
    HeadFactor=1,BackboneFactor=1);
fineTuneTraining = adni_train_resnet3d18( ...
    datasetRoot,Network=fineTuneNet, ...
    MaxEpochs=options.FineTuneEpochs, ...
    MiniBatchSize=1, ...
    InitialLearnRate=options.FineTuneLearnRate, ...
    L2Regularization=options.L2Regularization, ...
    ExecutionEnvironment="gpu", ...
    EnableCUDAForwardCompatibility= ...
        options.EnableCUDAForwardCompatibility, ...
    ValidationPatience=min(5,options.FineTuneEpochs), ...
    BatchNormalizationStatistics="moving", ...
    ResetInputNormalization=false, ...
    UseAugmentation=options.UseAugmentation, ...
    RandomSeed=options.RandomSeed+1, ...
    Verbose=options.Verbose);

manifestPath = fullfile(datasetRoot,"adni_3d_manifest.csv");
headValidation = adni_evaluate_resnet3d18( ...
    headTraining.Network,manifestPath, ...
    Split="validation",ExecutionEnvironment="gpu", ...
    BootstrapReplicates=0);
fineTuneValidation = adni_evaluate_resnet3d18( ...
    fineTuneTraining.Network,manifestPath, ...
    Split="validation",ExecutionEnvironment="gpu", ...
    BootstrapReplicates=0);

transfer = struct;
transfer.Initialization = initializationReport;
transfer.HeadScope = headScope;
transfer.HeadTraining = headTraining;
transfer.HeadValidation = headValidation;
transfer.FineTuneScope = fineTuneScope;
transfer.FineTuneTraining = fineTuneTraining;
transfer.FineTuneValidation = fineTuneValidation;
transfer.Options = rmfield( ...
    options,{'Network','InitializationReport'});
transfer.TestEvaluated = false;
transfer.CreatedAt = datetime("now",TimeZone="local");
if strlength(options.SaveFile) > 0
    save(options.SaveFile,"transfer","-v7.3");
end
end
