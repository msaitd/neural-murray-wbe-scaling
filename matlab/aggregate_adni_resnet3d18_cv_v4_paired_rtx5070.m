            log(medianGrid( ...
            foldDraws(replicate,:),seedDraws(replicate,:))),"all"));
        bootstrapRatios(replicate,comparisonIndex,2) = exp(mean( ...
            log(p95Grid( ...
            foldDraws(replicate,:),seedDraws(replicate,:))),"all"));
