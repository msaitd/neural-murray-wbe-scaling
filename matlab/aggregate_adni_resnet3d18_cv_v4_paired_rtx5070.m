function validate_benchmark_cell( ...
    value,fold,seed,methods,predictiveAnalysis)
assert(value.Passed && value.Fold == fold && value.Seed == seed && ...
    value.CellIndex == (fold-1)*5+(seed-20260820)+1 && ...
    value.WarmupIterations == 30 && value.TimingBlocks == 200 && ...
    value.CellBootstrapReplicates == 5000 && ...
    value.TimingRandomSeed == 20260830+value.CellIndex && ...
    value.SyntheticZeroInput && value.FreshMatlabProcess && ...
    value.InterleavedRandomizedOrder && value.GPUSynchronized && ...
    value.MemoryMetricIsRetainedAllocationProxyNotPeak && ...
    ~value.TrainingCallable && ~value.AllocationCallable && ...
    ~value.OuterTestPredictionCalled && ...
    isequal(value.NetworkNames(:),methods) && ...
    contains(value.Benchmark.Device,"RTX 5070",IgnoreCase=true), ...
    "NMA:InvalidCVV4RTX5070CellEnvelope", ...
    "Benchmark fold %d seed %d violates its frozen contract.",fold,seed);
raw = value.Benchmark.RawLatencySeconds;
orders = value.Benchmark.ExecutionOrders;
summary = value.Benchmark.Summary;
assert(isequal(size(raw),[200 3]) && all(isfinite(raw),"all") && ...
    all(raw > 0,"all") && isequal(size(orders),[200 3]) && ...
    all(sort(orders,2) == repmat(1:3,200,1),"all") && ...
    height(summary) == 3 && isequal(summary.Network,methods) && ...
    isequal(size(value.Benchmark.BootstrapLatencyRatio),[5000 3]) && ...
    isequal(size(value.Benchmark.BootstrapP95LatencyRatio),[5000 3]), ...
    "NMA:InvalidCVV4RTX5070CellTiming", ...
    "Benchmark fold %d seed %d has invalid raw timing data.",fold,seed);
medianLatency = median(raw,1).';
p95Latency = percentile_values(raw,95).';
assert(max(abs(summary.MedianLatencySeconds-medianLatency)) <= 1e-12 && ...
    max(abs(summary.LatencyP95Seconds-p95Latency)) <= 1e-12 && ...
    max(abs(summary.MedianLatencyRatioToBaseline- ...
    medianLatency/medianLatency(1))) <= 1e-12 && ...
    max(abs(summary.LatencyP95RatioToDense- ...
    p95Latency/p95Latency(1))) <= 1e-12 && ...
    all(summary.RetainedGPUAllocationProxyBytes >= 0), ...
    "NMA:IrreproducibleCVV4RTX5070CellSummary", ...
    "Benchmark fold %d seed %d cannot be reproduced.",fold,seed);
expected = predictiveAnalysis.PerCellMethod( ...
    predictiveAnalysis.PerCellMethod.Fold == fold & ...
    predictiveAnalysis.PerCellMethod.Seed == seed,:);
assert(height(expected) == 3, ...
    "NMA:MissingCVV4RTX5070PredictiveCell", ...
    "The predictive resource cell is missing.");
for methodIndex = 1:3
    expectedRow = expected(expected.Method == methods(methodIndex),:);
    assert(height(expectedRow) == 1 && ...
        summary.ParameterCount(methodIndex) == expectedRow.ParameterCount && ...
        summary.MACs(methodIndex) == expectedRow.MACs && ...
        summary.ActivationProxy(methodIndex) == ...
        expectedRow.ActivationProxy, ...
        "NMA:ChangedCVV4RTX5070CellNetwork", ...
        "A benchmark network differs from its predictive record.");
end
end

function tableValue = make_resource_summary(perCellMethod,methods)
records = repmat(empty_resource_record(),3,1);
denseRows = perCellMethod(perCellMethod.Method == "dense",:);
denseParameterMean = mean(denseRows.ParameterCount);
denseMACMean = mean(denseRows.MACs);
denseActivationMean = mean(denseRows.ActivationProxy);
for methodIndex = 1:3
    rows = perCellMethod(perCellMethod.Method == methods(methodIndex),:);
    parameterMean = mean(rows.ParameterCount);
    macMean = mean(rows.MACs);
    activationMean = mean(rows.ActivationProxy);
    records(methodIndex) = struct( ...
        "Method",methods(methodIndex),"Cells",height(rows), ...
        "ParameterMean",parameterMean, ...
        "ParameterMinimum",min(rows.ParameterCount), ...
        "ParameterMaximum",max(rows.ParameterCount), ...
        "ParameterFractionVsDense",parameterMean/denseParameterMean, ...
        "ParameterReductionVsDensePercent", ...
        100*(1-parameterMean/denseParameterMean), ...
        "MACMean",macMean,"MACMinimum",min(rows.MACs), ...
        "MACMaximum",max(rows.MACs), ...
        "MACFractionVsDense",macMean/denseMACMean, ...
        "MACReductionVsDensePercent",100*(1-macMean/denseMACMean), ...
        "ActivationProxyMean",activationMean, ...
        "ActivationProxyMinimum",min(rows.ActivationProxy), ...
        "ActivationProxyMaximum",max(rows.ActivationProxy), ...
        "ActivationFractionVsDense",activationMean/denseActivationMean, ...
        "ActivationReductionVsDensePercent", ...
        100*(1-activationMean/denseActivationMean));
end
tableValue = struct2table(records);
end

