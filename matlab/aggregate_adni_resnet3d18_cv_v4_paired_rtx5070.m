function values = percentile_values(data,percentages)
data = sort(data,1);
positions = 1+(size(data,1)-1)*(percentages(:)/100);
values = zeros(numel(percentages),size(data,2));
for index = 1:numel(percentages)
    lowerIndex = floor(positions(index));
    upperIndex = ceil(positions(index));
    weight = positions(index)-lowerIndex;
    values(index,:) = ...
        (1-weight)*data(lowerIndex,:)+weight*data(upperIndex,:);
end
if isscalar(percentages)
    values = values(1,:);
end
end

function metadata = collect_file_metadata(names,paths)
bytes = zeros(numel(paths),1);
modified = zeros(numel(paths),1);
sha256 = strings(numel(paths),1);
for index = 1:numel(paths)
    information = dir(paths(index));
    assert(isscalar(information), ...
        "NMA:CVV4RTX5070MetadataFailure", ...
        "Could not inspect a benchmark-analysis input.");
    bytes(index) = information.bytes;
    modified(index) = information.datenum;
    sha256(index) = file_sha256(paths(index));
end
metadata = table( ...
    names,paths,bytes,modified,sha256, ...
    VariableNames=["Name","Path","Bytes","Modified","SHA256"]);
end

function validate_metadata(metadata,errorIdentifier)
hasDigest = ismember("SHA256",string(metadata.Properties.VariableNames));
for index = 1:height(metadata)
    information = dir(metadata.Path(index));
    valid = isscalar(information) && ...
        information.bytes == metadata.Bytes(index) && ...
        information.datenum == metadata.Modified(index);
    if valid && hasDigest
        valid = file_sha256(metadata.Path(index)) == metadata.SHA256(index);
    end
    assert(valid,errorIdentifier, ...
        "A frozen benchmark input changed: %s",metadata.Path(index));
end
end

function digest = file_sha256(path)
fileIdentifier = fopen(path,"rb");
assert(fileIdentifier >= 0,"NMA:CVV4RTX5070HashReadFailure", ...
    "Could not open a benchmark input for hashing: %s",path);
cleanup = onCleanup(@() fclose(fileIdentifier));
bytes = fread(fileIdentifier,Inf,"*uint8");
messageDigest = java.security.MessageDigest.getInstance("SHA-256");
messageDigest.update(bytes);
raw = typecast(messageDigest.digest(),"uint8");
digest = lower(join(compose("%02x",raw),""));
clear cleanup
end

