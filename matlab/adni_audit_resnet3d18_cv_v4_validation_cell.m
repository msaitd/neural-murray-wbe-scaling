    initialization.net,contract.HeadSeed);
[resetB,reportB] = adni_resnet3d18_reset_classifier( ...
    initialization.net,contract.HeadSeed);
training = artifact.Training;
assert(initialization.report.Method == ...
    "ImageNet-2D-to-3D-kernel-inflation" && ...
    initialization.report.TotalLearnableParameters == 33166339 && ...
    isequal(initialization.report.Widths,[64;128;256;512]) && ...
    isequaln(artifact.InitializationReport,initialization.report) && ...
    network_values_equal(resetA,resetB) && ...
    reportA.RandomSeed == contract.HeadSeed && ...
    reportB.RandomSeed == contract.HeadSeed && ...
    reportA.BackboneExact && reportB.BackboneExact && ...
    reportA.OutputSize == 3 && reportA.InputSize == 512 && ...
    artifact.ClassifierReset.RandomSeed == reportA.RandomSeed && ...
    artifact.ClassifierReset.Initializer == reportA.Initializer && ...
    artifact.ClassifierReset.OutputSize == reportA.OutputSize && ...
    artifact.ClassifierReset.InputSize == reportA.InputSize && ...
    artifact.ClassifierReset.BackboneExact && ...
    abs(artifact.ClassifierReset.WeightMean-reportA.WeightMean) <= ...
    1e-15 && ...
    abs(artifact.ClassifierReset.WeightStandardDeviation- ...
    reportA.WeightStandardDeviation) <= 1e-15 && ...
    artifact.Type == "dense-head-training" && ...
    isequaln(artifact.Contract,contract) && artifact.Passed && ...
    ~artifact.OuterTestEvaluated && ...
    artifact.HeadScope.Scope == "head-only" && ...
    artifact.HeadScope.NumFrozenTensors > 0 && ...
    ~training.TestEvaluated && ...
    isequal(training.Widths,[64;128;256;512]) && ...
    training.TrainRows == splitAudit.NumTrainRows && ...
    training.TrainSubjects == splitAudit.NumTrainSubjects && ...
    training.ValidationRows == splitAudit.NumValidationRows && ...
    training.ValidationSubjects == splitAudit.NumValidationSubjects && ...
    training.Options.MaxEpochs == 1 && ...
    training.Options.MiniBatchSize == 1 && ...
    training.Options.InitialLearnRate == 1e-3 && ...
    training.Options.L2Regularization == 1e-4 && ...
    training.Options.ExecutionEnvironment == "gpu" && ...
    training.Options.DeterministicGPU && ...
    training.Options.ValidationPatience == 1 && ...
    training.Options.BatchNormalizationStatistics == "moving" && ...
    training.Options.ResetInputNormalization && ...
    training.Options.UseAugmentation && ...
    training.Options.RandomSeed == contract.HeadSeed && ...
    training.BestValidation.Split == "validation" && ...
    training.BestValidation.NumSubjects == ...
    splitAudit.NumValidationSubjects && ...
    network_is_finite(training.Network), ...
