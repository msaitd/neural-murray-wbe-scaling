function audit = ...
    adni_audit_resnet3d18_cv_v4_validation_cell(fold,seed,options)
%ADNI_AUDIT_RESNET3D18_CV_V4_VALIDATION_CELL Audit one sealed v4 cell.
%
% This function independently reloads every stage artifact, reconstructs
% the training-only allocation and inherited-channel surgery, and
% reproduces validation predictions. It never evaluates the outer test.

arguments
    fold (1,1) double {mustBeInteger,mustBeInRange(fold,1,5)}
    seed (1,1) double {mustBeInteger}
    options.OutputRoot (1,1) string = ""
    options.Verbose (1,1) logical = true
end

assert(ismember(seed,20260820:20260824), ...
    "NMA:InvalidCVV4AuditSeed", ...
    "Seed %d is not one of the locked v4 seeds.",seed);
scriptDirectory = fileparts(mfilename("fullpath"));
projectRoot = fileparts(scriptDirectory);
workRoot = fullfile(projectRoot,"adni_work");
trainingRoot = fullfile( ...
    workRoot,"adni_3d_cv_v4", ...
    "locked_internal_validation_training");
cellRoot = fullfile( ...
    trainingRoot,"fold_"+fold,"seed_"+seed);
manifestFile = fullfile( ...
    workRoot,"adni_3d_cv_v2","fold_"+fold, ...
    "adni_3d_manifest.csv");
initializationFile = fullfile( ...
    workRoot,"adni_resnet3d18_imagenet_initialization.mat");
preflightFile = fullfile( ...
    workRoot,"adni_3d_cv_v4","full_validation_preflight", ...
    "v4_full_validation_preflight.mat");
runFile = fullfile( ...
    trainingRoot,"v4_validation_training_result.mat");
cellResultFile = fullfile(cellRoot,"validation_cell_result.mat");
headFile = fullfile(cellRoot,"dense_head_training.mat");
denseFile = fullfile(cellRoot,"dense_teacher_training.mat");
calibrationFile = fullfile( ...
    cellRoot,"training_calibration_allocation.mat");
proportionalFile = fullfile( ...
    cellRoot,"proportional_student_training.mat");
nmaFile = fullfile( ...
    cellRoot,"multi_resource_nma_student_training.mat");
auditSourceFile = string([mfilename("fullpath") ".m"]);
inputNames = [ ...
    "manifest";"raw_initialization";"full_preflight"; ...
    "full_training_run";"cell_result";"head_artifact"; ...
    "dense_artifact";"calibration_artifact"; ...
    "proportional_artifact";"nma_artifact";"audit_source"];
inputPaths = [ ...
    manifestFile;initializationFile;preflightFile;runFile; ...
    cellResultFile;headFile;denseFile;calibrationFile; ...
    proportionalFile;nmaFile;auditSourceFile];
assert(all(isfile(inputPaths)), ...
    "NMA:MissingCVV4CellAuditInput", ...
    "A required full-validation cell-audit input is missing.");
inputMetadata = collect_file_metadata(inputNames,inputPaths);

if strlength(options.OutputRoot) == 0
    outputRoot = fullfile( ...
        workRoot,"adni_3d_cv_v4","pretest_audit_cells", ...
        "fold_"+fold,"seed_"+seed);
else
    outputRoot = options.OutputRoot;
end
assert(startsWith( ...
    lower(string(outputRoot)),lower(string(workRoot)+filesep)), ...
    "NMA:InvalidCVV4CellAuditOutputRoot", ...
    "The v4 cell-audit output must remain under adni_work.");
if ~isfolder(outputRoot)
    mkdir(outputRoot);
end
outputFile = fullfile(outputRoot,"audit_cell_result.mat");
if isfile(outputFile)
    source = load(outputFile,"audit");
    audit = source.audit;
    validate_reusable_audit(audit,fold,seed,inputMetadata);
    fprintf( ...
        "Loaded completed v4 audit fold %d seed %d.\n",fold,seed);
    return
end

preflightSource = load(preflightFile,"preflight");
runSource = load(runFile,"run");
cellSource = load(cellResultFile,"cellResult");
headSource = load(headFile,"headArtifact");
denseSource = load(denseFile,"denseArtifact");
calibrationSource = load(calibrationFile,"calibrationArtifact");
proportionalSource = load( ...
    proportionalFile,"proportionalArtifact");
nmaSource = load(nmaFile,"nmaArtifact");
preflight = preflightSource.preflight;
runResult = runSource.run;
cellResult = cellSource.cellResult;
headArtifact = headSource.headArtifact;
denseArtifact = denseSource.denseArtifact;
calibrationArtifact = calibrationSource.calibrationArtifact;
proportionalArtifact = proportionalSource.proportionalArtifact;
nmaArtifact = nmaSource.nmaArtifact;

validate_preflight_and_run( ...
    preflight,runResult,preflightFile,fold,seed,cellResultFile);
manifest = readtable( ...
    manifestFile,Delimiter=",",TextType="string", ...
    VariableNamingRule="preserve");
splitAudit = validate_manifest(manifest,fold);
contract = validate_contract( ...
    cellResult,fold,seed,cellRoot,preflightFile,splitAudit);
artifactFiles = [ ...
    headFile;denseFile;calibrationFile;proportionalFile;nmaFile];
currentArtifactStamps = repmat(empty_stamp(),5,1);
for index = 1:5
    currentArtifactStamps(index) = file_stamp(artifactFiles(index));
end
assert(isequal(cellResult.StageArtifactFiles,artifactFiles) && ...
    all(arrayfun(@(index) stamp_matches( ...
    currentArtifactStamps(index), ...
    cellResult.StageArtifactStamps(index)),1:5)), ...
    "NMA:ChangedCVV4AuditStageArtifact", ...
    "A v4 stage artifact changed after cell completion.");

validate_initialization( ...
    initializationFile,headArtifact,contract,splitAudit);
validate_dense( ...
    denseArtifact,contract,splitAudit,headFile);
validate_calibration_envelope( ...
    calibrationArtifact,contract,splitAudit,denseFile,manifest);
validate_student( ...
    proportionalArtifact,"proportional",contract,splitAudit, ...
    denseFile,calibrationFile);
validate_student( ...
    nmaArtifact,"multi-resource-NMA",contract,splitAudit, ...
    denseFile,calibrationFile);

trainRows = manifest(manifest.split == "train",:);
previousDeterminism = deep.gpu.deterministicAlgorithms(true);
previousGPUGenerator = gpurng;
determinismCleanup = onCleanup(@() restore_gpu_state( ...
    previousDeterminism,previousGPUGenerator));
gpurng(seed+2,"Threefry");
reproducedCalibration = nma_resnet3d18_calibrate( ...
    denseArtifact.Training.Network, ...
    trainRows.matPath,trainRows.classIndex, ...
    MiniBatchSize=1,MaxBatches=Inf,UseGPU=true, ...
    ClassWeights=calibrationArtifact.ClassWeights, ...
    Verbose=options.Verbose,ProgressFrequency=25);
clear determinismCleanup
restore_gpu_state(previousDeterminism,previousGPUGenerator);
calibrationError = calibration_maximum_error( ...
    calibrationArtifact.Calibration,reproducedCalibration);
assert(calibrationError <= 1e-7, ...
    "NMA:CVV4AuditCalibrationReproductionMismatch", ...
    "Fold %d seed %d calibration error is %.9g.", ...
    fold,seed,calibrationError);

[reproducedAllocation,budgetFractions] = ...
    reproduce_allocation(reproducedCalibration);
assert(isequal(reproducedAllocation.TargetWidths, ...
    calibrationArtifact.NMAAllocation.TargetWidths) && ...
    isequal(reproducedAllocation.ProjectedResources, ...
    calibrationArtifact.NMAAllocation.ProjectedResources), ...
    "NMA:CVV4AuditAllocationReproductionMismatch", ...
    "Fold %d seed %d NMA allocation did not reproduce.",fold,seed);
[rebuiltProportional,proportionalSurgery] = ...
    nma_resnet3d18_rebuild( ...
    denseArtifact.Training.Network, ...
    calibrationArtifact.ProportionalAllocation, ...
    reproducedCalibration);
[rebuiltNMA,nmaSurgery] = nma_resnet3d18_rebuild( ...
    denseArtifact.Training.Network,reproducedAllocation, ...
    reproducedCalibration);
assert(surgery_matches( ...
    proportionalSurgery,proportionalArtifact.Surgery) && ...
    surgery_matches(nmaSurgery,nmaArtifact.Surgery) && ...
    sum(cellfun(@numel,rebuiltProportional.Learnables.Value)) == ...
    24923027 && ...
    sum(cellfun(@numel,rebuiltNMA.Learnables.Value)) == ...
    nmaArtifact.Surgery.CompressedLearnableParameters, ...
    "NMA:CVV4AuditSurgeryReproductionMismatch", ...
    "Fold %d seed %d inherited-channel surgery did not reproduce.", ...
    fold,seed);
clear rebuiltProportional rebuiltNMA

denseEvaluation = reproduce_validation( ...
    denseArtifact.Training.Network,manifestFile, ...
    denseArtifact.Training.BestValidation, ...
    cellResult.DenseValidation,splitAudit.NumValidationSubjects);
proportionalEvaluation = reproduce_validation( ...
    proportionalArtifact.Training.Network,manifestFile, ...
    proportionalArtifact.Training.BestValidation, ...
    cellResult.ProportionalValidation, ...
    splitAudit.NumValidationSubjects);
nmaEvaluation = reproduce_validation( ...
    nmaArtifact.Training.Network,manifestFile, ...
    nmaArtifact.Training.BestValidation, ...
    cellResult.NMAValidation,splitAudit.NumValidationSubjects);
verifiedSummary = verify_summary( ...
    cellResult.ValidationSummary, ...
    {denseEvaluation;proportionalEvaluation;nmaEvaluation}, ...
    calibrationArtifact.NMAAllocation.TargetWidths);

audit = struct;
audit.Design = "independent v4 validation-cell pre-test audit";
audit.Fold = fold;
audit.Seed = seed;
audit.InputMetadata = inputMetadata;
audit.Contract = contract;
audit.SplitAudit = splitAudit;
audit.StageArtifactFiles = artifactFiles;
audit.StageArtifactStamps = currentArtifactStamps;
audit.VerifiedSummary = verifiedSummary;
audit.NMAWidths = reproducedAllocation.TargetWidths;
audit.BudgetFractions = budgetFractions;
audit.CalibrationMaximumError = calibrationError;
audit.InitializationReproduced = true;
audit.TrainingArtifactsValidated = 3;
audit.SupportArtifactsValidated = 2;
audit.CalibrationReproduced = true;
audit.AllocationReproduced = true;
audit.SurgeryReproduced = true;
audit.AllValidationPredictionsReproduced = true;
audit.NoPostHocSelection = true;
audit.PredictiveMetricsForInference = false;
audit.OuterTestPredictionsComputed = false;
audit.OuterTestEvaluated = false;
audit.OuterTestSealed = true;
audit.Passed = true;
audit.ValidatedAt = datetime("now",TimeZone="local");
atomic_save(outputFile,"audit",audit);
writetable(verifiedSummary,fullfile( ...
    outputRoot,"verified_validation_summary.csv"),Encoding="UTF-8");
fprintf( ...
    ["ADNI_RESNET3D18_CV_V4_VALIDATION_CELL_AUDIT_PASS " ...
    "fold %d seed %d calibrationError %.9g\n"], ...
    fold,seed,calibrationError);
end

function validate_reusable_audit(audit,fold,seed,inputMetadata)
assert(audit.Passed && audit.Fold == fold && audit.Seed == seed && ...
    audit.InitializationReproduced && ...
    audit.TrainingArtifactsValidated == 3 && ...
    audit.SupportArtifactsValidated == 2 && ...
    audit.CalibrationReproduced && audit.AllocationReproduced && ...
    audit.SurgeryReproduced && ...
    audit.AllValidationPredictionsReproduced && ...
    audit.NoPostHocSelection && ...
    ~audit.PredictiveMetricsForInference && ...
    ~audit.OuterTestPredictionsComputed && ...
    ~audit.OuterTestEvaluated && audit.OuterTestSealed && ...
    isequaln(audit.InputMetadata,inputMetadata), ...
    "NMA:InvalidReusableCVV4CellAudit", ...
    "A saved v4 cell audit is stale or invalid.");
end

function validate_preflight_and_run( ...
    preflight,runResult,preflightFile,fold,seed,cellResultFile)
assert(preflight.Passed && ...
    preflight.Phase2ValidationTrainingAuthorized && ...
    preflight.SmokeValidationPassed && ...
    preflight.NumFolds == 5 && preflight.NumSeeds == 5 && ...
    preflight.NumCells == 25 && preflight.OuterTestSealed && ...
    ~preflight.TrainingPerformed && ...
    ~preflight.OuterTestPredictionsComputed && ...
    ~preflight.OuterTestEvaluated, ...
    "NMA:InvalidCVV4AuditPreflight", ...
    "The sealed full-validation preflight is invalid.");
for index = 1:height(preflight.InputMetadata)
    information = dir(preflight.InputMetadata.Path(index));
    assert(isscalar(information) && ...
        information.bytes == preflight.InputMetadata.Bytes(index) && ...
        information.datenum == ...
        preflight.InputMetadata.Modified(index), ...
        "NMA:ChangedCVV4AuditPreflightInput", ...
        "A full-validation preflight input changed: %s", ...
        preflight.InputMetadata.Path(index));
end
assert(runResult.Passed && ...
    runResult.ReadyForIndependentPreTestAudit && ...
    runResult.CompletedCells == 25 && ...
    runResult.CompletedDenseTeachers == 25 && ...
    runResult.CompletedCompressedStudents == 50 && ...
    runResult.TotalNetworks == 75 && ...
    ~runResult.PredictiveMetricsForInference && ...
    ~runResult.OuterTestPredictionsComputed && ...
    ~runResult.OuterTestEvaluated && runResult.OuterTestSealed && ...
    stamp_matches(runResult.PreflightStamp,file_stamp(preflightFile)) && ...
    height(runResult.PerCellMethodSummary) == 75 && ...
    numel(runResult.Records) == 25, ...
    "NMA:InvalidCVV4AuditTrainingRun", ...
    "The completed v4 validation-training envelope is invalid.");
cellIndex = (fold-1)*5+(seed-20260820)+1;
record = runResult.Records(cellIndex);
resultStamp = file_stamp(cellResultFile);
assert(record.Passed && record.CellIndex == cellIndex && ...
    record.Fold == fold && record.Seed == seed && ...
    string(record.ResultFile) == string(cellResultFile) && ...
    record.ResultFileBytes == resultStamp.Bytes && ...
    record.ResultFileModified == resultStamp.Modified && ...
    ~record.OuterTestEvaluated, ...
    "NMA:InvalidCVV4AuditCellRecord", ...
    "The aggregate record for fold %d seed %d is invalid.",fold,seed);
end

function splitAudit = validate_manifest(manifest,fold)
required = [ ...
    "subject","imageDataId","group","classIndex", ...
    "split","visit","matPath"];
assert(all(ismember(required, ...
    string(manifest.Properties.VariableNames))) && ...
    all(isfile(manifest.matPath)) && ...
    height(manifest) == numel(unique(manifest.imageDataId)), ...
    "NMA:InvalidCVV4AuditManifest", ...
    "Fold %d manifest columns, paths, or image identifiers changed.",fold);
trainRows = manifest(manifest.split == "train",:);
validationRows = manifest(manifest.split == "validation",:);
testRows = manifest(manifest.split == "test",:);
trainSubjects = unique(trainRows.subject);
validationSubjects = unique(validationRows.subject);
testSubjects = unique(testRows.subject);
expectedTrainRows = [1146;1149;1152;1155;1149];
expectedTrainSubjects = [382;383;384;385;383];
expectedValidationSubjects = [128;128;127;127;129];
expectedTestSubjects = [129;128;128;127;127];
trainMultiplicity = groupcounts(categorical(trainRows.subject));
assert(height(trainRows) == expectedTrainRows(fold) && ...
    numel(trainSubjects) == expectedTrainSubjects(fold) && ...
    all(trainMultiplicity == 3) && ...
    height(validationRows) == expectedValidationSubjects(fold) && ...
    numel(validationSubjects) == expectedValidationSubjects(fold) && ...
    height(testRows) == expectedTestSubjects(fold) && ...
    numel(testSubjects) == expectedTestSubjects(fold) && ...
    numel(unique([trainSubjects;validationSubjects;testSubjects])) == 639 && ...
    all(validationRows.visit == "sc") && ...
    all(testRows.visit == "sc") && ...
    isempty(intersect(trainSubjects,validationSubjects)) && ...
    isempty(intersect(trainSubjects,testSubjects)) && ...
    isempty(intersect(validationSubjects,testSubjects)) && ...
    all(manifest.classIndex(manifest.group == "AD") == 1) && ...
    all(manifest.classIndex(manifest.group == "CN") == 2) && ...
    all(manifest.classIndex(manifest.group == "MCI") == 3), ...
    "NMA:CVV4AuditSplitContractViolation", ...
    "Fold %d violates the locked participant split.",fold);
splitAudit = struct;
splitAudit.NumTrainRows = height(trainRows);
splitAudit.NumTrainSubjects = numel(trainSubjects);
splitAudit.NumValidationRows = height(validationRows);
splitAudit.NumValidationSubjects = numel(validationSubjects);
splitAudit.NumTestRows = height(testRows);
splitAudit.NumTestSubjects = numel(testSubjects);
splitAudit.OuterTestEvaluated = false;
end

