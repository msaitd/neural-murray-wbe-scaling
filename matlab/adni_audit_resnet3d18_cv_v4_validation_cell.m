    channelErrors = [ ...
        max(abs(first.Probes.ForwardByChannel{index}- ...
        second.Probes.ForwardByChannel{index}),[],"all"); ...
        max(abs(first.Probes.BackwardByChannel{index}- ...
        second.Probes.BackwardByChannel{index}),[],"all"); ...
        max(abs(first.Probes.MultiplicativeByChannel{index}- ...
        second.Probes.MultiplicativeByChannel{index}),[],"all")];
    maximumError = max(maximumError,max(channelErrors));
