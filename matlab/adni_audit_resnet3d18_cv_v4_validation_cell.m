    evaluation = evaluations{index};
    parameterCount = nma_resnet3d18_resource( ...
        widths(index,:).',Resource="parameters",NumClasses=3);
    macs = nma_resnet3d18_resource( ...
        widths(index,:).',Resource="macs",NumClasses=3);
