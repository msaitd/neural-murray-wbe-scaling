end

function matches = surgery_matches(first,second)
matches = isequal(first.TargetWidths,second.TargetWidths) && ...
    first.CompressedLearnableParameters == ...
    second.CompressedLearnableParameters && ...
    first.CompressedMACs == second.CompressedMACs && ...
    first.CompressedActivationProxy == ...
    second.CompressedActivationProxy && ...
    numel(first.StageMasks) == numel(second.StageMasks);
if ~matches
    return
end
for stage = 1:numel(first.StageMasks)
    if ~isequal(first.StageMasks{stage},second.StageMasks{stage})
        matches = false;
        return
    end
end
firstFields = sort(string(fieldnames(first.HiddenMasks)));
secondFields = sort(string(fieldnames(second.HiddenMasks)));
if ~isequal(firstFields,secondFields)
    matches = false;
    return
end
for index = 1:numel(firstFields)
    field = firstFields(index);
    if ~isequal(first.HiddenMasks.(field),second.HiddenMasks.(field))
        matches = false;
        return
    end
end
end

