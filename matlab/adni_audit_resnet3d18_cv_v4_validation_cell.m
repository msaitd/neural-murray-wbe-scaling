        evaluation.BalancedAccuracy) <= 1e-12 && ...
        abs(summary.MacroF1(index)-evaluation.MacroF1) <= 1e-12 && ...
        abs(summary.Accuracy(index)-evaluation.Accuracy) <= 1e-12 && ...
