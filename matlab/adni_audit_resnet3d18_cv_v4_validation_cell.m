function validate_calibration_envelope( ...
    artifact,contract,splitAudit,denseFile,manifest)
trainRows = manifest(manifest.split == "train",:);
expectedRows = trainRows(:,[ ...
    "subject","imageDataId","group","classIndex","visit","matPath"]);
classNames = ["AD";"CN";"MCI"];
classCounts = zeros(3,1);
for index = 1:3
    classCounts(index) = sum(trainRows.group == classNames(index));
end
classWeights = sum(classCounts)./(3*classCounts);
classWeights = classWeights/mean(classWeights);
nmaResources = artifact.NMAAllocation.ResourceTable;
assert(artifact.Type == "training-calibration-allocation" && ...
    isequaln(artifact.Contract,contract) && ...
    stamp_matches(artifact.DenseArtifactStamp,file_stamp(denseFile)) && ...
    artifact.Passed && artifact.TrainingOnly && ...
    ~artifact.ValidationDataUsed && ~artifact.OuterTestEvaluated && ...
    isequal(artifact.CalibrationRows,expectedRows) && ...
    isequal(artifact.ClassCounts,classCounts) && ...
    max(abs(artifact.ClassWeights(:)-classWeights(:))) <= 1e-12 && ...
    height(artifact.CalibrationRows) == splitAudit.NumTrainRows && ...
    artifact.Calibration.NumImages == splitAudit.NumTrainRows && ...
    artifact.Calibration.NumBatches == splitAudit.NumTrainRows && ...
    artifact.Calibration.MiniBatchSize == 1 && ...
    artifact.Calibration.UseGPU && ...
    isequal(artifact.Calibration.Spec.BaselineWidths, ...
    [64;128;256;512]) && ...
    all(isfinite(artifact.Calibration.Losses)) && ...
    all(isfinite( ...
    artifact.Calibration.StageDemand.MultiplicativeMeanAbs)) && ...
    artifact.ParameterCeiling == 24923027 && ...
    artifact.MACCeiling == 9865390056 && ...
    artifact.NMAAllocation.Estimator == "multiplicative" && ...
    artifact.NMAAllocation.P == 2 && ...
    isequal(artifact.NMAAllocation.Resources,["parameters";"macs"]) && ...
    all(mod(artifact.NMAAllocation.TargetWidths,[4;8;8;8]) == 0) && ...
    all(artifact.NMAAllocation.TargetWidths >= [32;64;128;256]) && ...
    all(artifact.NMAAllocation.TargetWidths <= [64;128;256;512]) && ...
    all(nmaResources.Projected <= ...
    nmaResources.Budget*(1+1e-12)) && ...
    isequal(artifact.ProportionalAllocation.TargetWidths, ...
    [52;120;224;440]) && ...
    isequal(artifact.ProportionalAllocation.ProjectedResources, ...
    [24923027;9865390056]), ...
    "NMA:InvalidCVV4AuditCalibrationEnvelope", ...
    "The training-only calibration/allocation envelope is invalid.");
end

function validate_student( ...
    artifact,method,contract,splitAudit,denseFile,calibrationFile)
training = artifact.Training;
actualParameters = sum(cellfun(@numel,training.Network.Learnables.Value));
analyticalParameters = nma_resnet3d18_resource( ...
    artifact.Allocation.TargetWidths, ...
    Resource="parameters",NumClasses=3);
analyticalMACs = nma_resnet3d18_resource( ...
    artifact.Allocation.TargetWidths,Resource="macs",NumClasses=3);
