function equal = network_values_equal(first,second)
equal = isequal(first.Learnables.Layer,second.Learnables.Layer) && ...
    isequal(first.Learnables.Parameter,second.Learnables.Parameter) && ...
    isequal(first.State.Layer,second.State.Layer) && ...
    isequal(first.State.Parameter,second.State.Parameter) && ...
    height(first.Learnables) == height(second.Learnables) && ...
    height(first.State) == height(second.State);
if ~equal
    return
end
for row = 1:height(first.Learnables)
    if ~isequal(cpu_data(first.Learnables.Value{row}), ...
            cpu_data(second.Learnables.Value{row}))
        equal = false;
        return
    end
end
for row = 1:height(first.State)
    if ~isequal(cpu_data(first.State.Value{row}), ...
            cpu_data(second.State.Value{row}))
        equal = false;
        return
    end
end
end

function valid = network_is_finite(network)
valid = all(cellfun(@(value) ...
    all(isfinite(cpu_data(value)),"all"), ...
    network.Learnables.Value));
end

function value = cpu_data(input)
if isa(input,"dlarray")
    value = extractdata(input);
else
    value = input;
end
if isa(value,"gpuArray")
    value = gather(value);
end
end

function metadata = collect_file_metadata(names,paths)
bytes = zeros(numel(paths),1);
modified = zeros(numel(paths),1);
for index = 1:numel(paths)
    information = dir(paths(index));
    assert(isscalar(information), ...
        "NMA:CVV4CellAuditMetadataFailure", ...
        "Could not inspect a v4 cell-audit input.");
    bytes(index) = information.bytes;
    modified(index) = information.datenum;
end
metadata = table( ...
    names,paths,bytes,modified, ...
    VariableNames=["Name","Path","Bytes","Modified"]);
end

function stamp = file_stamp(path)
information = dir(path);
assert(isscalar(information), ...
    "NMA:CVV4CellAuditStampFailure", ...
    "Could not inspect v4 audit file %s.",path);
stamp = struct( ...
    "Path",string(path),"Bytes",information.bytes, ...
    "Modified",information.datenum);
end

function stamp = empty_stamp()
stamp = struct("Path","","Bytes",0,"Modified",0);
end

function matches = stamp_matches(first,second)
matches = first.Path == second.Path && ...
    first.Bytes == second.Bytes && ...
    first.Modified == second.Modified;
end

