assert(all(isfile([ ...
    string(preflightFile);string(releaseFile); ...
    string(validationFile);sourceFile])), ...
    "NMA:MissingCVV4OuterAnalysisInput", ...
    "The preflight, atomic release, and independent validation are required.");

