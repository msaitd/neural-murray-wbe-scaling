%% Locked participant-pooled repeated-seed analysis of the v4 outer release.
addpath(fileparts(mfilename("fullpath")));

scriptDirectory = fileparts(mfilename("fullpath"));
projectRoot = fileparts(scriptDirectory);
workRoot = fullfile(projectRoot,"adni_work");
preflightFile = fullfile( ...
    workRoot,"adni_3d_cv_v4","phase4_atomic_preflight", ...
    "v4_phase4_atomic_preflight.mat");
releaseFile = fullfile( ...
    workRoot,"adni_3d_cv_v4","atomic_outer_test", ...
    "v4_atomic_outer_test_release.mat");
validationFile = fullfile( ...
    workRoot,"adni_3d_cv_v4","atomic_outer_test_validation", ...
    "v4_atomic_outer_test_validation.mat");
