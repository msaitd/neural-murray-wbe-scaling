function indices = stratified_participant_draw(truth,classNames)
indices = zeros(numel(truth),1);
next = 1;
for classIndex = 1:numel(classNames)
    classRows = find(truth == classNames(classIndex));
    count = numel(classRows);
    assert(count > 0,"NMA:MissingCVV4BootstrapClass", ...
        "Every class must occur in the hierarchical bootstrap.");
    indices(next:next+count-1) = classRows(randi(count,count,1));
    next = next+count;
end
end

function p = two_sided_bootstrap_p(distribution)
replicates = numel(distribution);
lower = (sum(distribution <= 0)+1)/(replicates+1);
upper = (sum(distribution >= 0)+1)/(replicates+1);
p = min(1,2*min(lower,upper));
end

function [adjusted,rankOrder,stepAlpha] = holm_adjustment(pValues,alpha)
[sortedP,order] = sort(pValues);
count = numel(pValues);
adjustedSorted = zeros(count,1);
alphaSorted = zeros(count,1);
running = 0;
for rank = 1:count
    adjustedSorted(rank) = min(1,max(running,(count-rank+1)*sortedP(rank)));
    running = adjustedSorted(rank);
    alphaSorted(rank) = alpha/(count-rank+1);
end
adjusted = zeros(count,1);
stepAlpha = zeros(count,1);
adjusted(order) = adjustedSorted;
stepAlpha(order) = alphaSorted;
rankOrder = order;
end

function grid = balanced_accuracy_grid(perCellMethod,method,seeds)
rows = perCellMethod(perCellMethod.Method == method,:);
grid = zeros(5,numel(seeds));
for fold = 1:5
    for seedIndex = 1:numel(seeds)
        value = rows.BalancedAccuracy( ...
            rows.Fold == fold & rows.Seed == seeds(seedIndex));
        assert(isscalar(value),"NMA:MissingCVV4VarianceCell", ...
            "A fold-seed balanced-accuracy cell is missing.");
        grid(fold,seedIndex) = value;
    end
end
end

function record = empty_variance_record()
record = struct( ...
    "Outcome","","GrandMean",NaN,"FoldVariance",NaN, ...
    "SeedVariance",NaN,"ResidualFoldSeedVariance",NaN, ...
    "FoldShare",NaN,"SeedShare",NaN,"ResidualShare",NaN, ...
    "NegativeComponentsTruncated",false);
end

function record = variance_record(outcome,grid)
numFolds = size(grid,1);
numSeeds = size(grid,2);
grandMean = mean(grid,"all");
foldMeans = mean(grid,2);
seedMeans = mean(grid,1);
ssFold = numSeeds*sum((foldMeans-grandMean).^2);
ssSeed = numFolds*sum((seedMeans-grandMean).^2);
residual = grid-foldMeans-seedMeans+grandMean;
ssResidual = sum(residual.^2,"all");
msFold = ssFold/(numFolds-1);
msSeed = ssSeed/(numSeeds-1);
msResidual = ssResidual/((numFolds-1)*(numSeeds-1));
rawFold = (msFold-msResidual)/numSeeds;
rawSeed = (msSeed-msResidual)/numFolds;
foldVariance = max(rawFold,0);
seedVariance = max(rawSeed,0);
residualVariance = max(msResidual,0);
total = foldVariance+seedVariance+residualVariance;
if total > 0
    shares = [foldVariance,seedVariance,residualVariance]/total;
else
    shares = [0 0 0];
end
record = struct( ...
    "Outcome",outcome,"GrandMean",grandMean, ...
    "FoldVariance",foldVariance,"SeedVariance",seedVariance, ...
    "ResidualFoldSeedVariance",residualVariance, ...
    "FoldShare",shares(1),"SeedShare",shares(2), ...
    "ResidualShare",shares(3), ...
    "NegativeComponentsTruncated",rawFold < 0 || rawSeed < 0);
end

function values = percentile_values(data,percentages)
data = sort(data(:));
positions = 1+(numel(data)-1)*(percentages(:)/100);
values = zeros(numel(percentages),1);
for index = 1:numel(percentages)
    lowerIndex = floor(positions(index));
    upperIndex = ceil(positions(index));
    weight = positions(index)-lowerIndex;
    values(index) = ...
        (1-weight)*data(lowerIndex)+weight*data(upperIndex);
end
end

function metadata = collect_file_metadata(names,paths)
bytes = zeros(numel(paths),1);
modified = zeros(numel(paths),1);
for index = 1:numel(paths)
    information = dir(paths(index));
    assert(isscalar(information), ...
        "NMA:CVV4OuterAnalysisMetadataFailure", ...
        "Could not inspect a locked analysis input.");
    bytes(index) = information.bytes;
    modified(index) = information.datenum;
end
metadata = table( ...
    names,paths,bytes,modified, ...
    VariableNames=["Name","Path","Bytes","Modified"]);
end

function validate_metadata(metadata,errorIdentifier)
for index = 1:height(metadata)
    information = dir(metadata.Path(index));
    assert(isscalar(information) && ...
        information.bytes == metadata.Bytes(index) && ...
        information.datenum == metadata.Modified(index), ...
        errorIdentifier, ...
        "A locked outer-analysis input changed: %s",metadata.Path(index));
end
end

