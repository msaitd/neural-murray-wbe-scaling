parallel.gpu.enableCUDAForwardCompatibility(true);

scriptDirectory = fileparts(mfilename("fullpath"));
projectRoot = fileparts(scriptDirectory);
workRoot = fullfile(projectRoot,"adni_work");
outputRoot = fullfile( ...
    workRoot,"adni_3d_cv_v4","engineering_smoke");
cellOutputRoot = fullfile( ...
    outputRoot,"fold_1","seed_20260820");
if ~isfolder(outputRoot)
    mkdir(outputRoot);
end

firstInvocation = adni_run_resnet3d18_cv_v4_validation_cell( ...
    1,20260820,Mode="engineering-smoke", ...
    OutputRoot=cellOutputRoot,Verbose=true);
