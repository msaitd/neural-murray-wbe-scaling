secondInvocation = adni_run_resnet3d18_cv_v4_validation_cell( ...
    1,20260820,Mode="engineering-smoke", ...
    OutputRoot=cellOutputRoot,Verbose=true);
secondArtifactStamps = secondInvocation.StageArtifactStamps;
assert(secondInvocation.AllStageArtifactsReused && ...
    all(secondInvocation.StageArtifactReused) && ...
    isequaln(firstArtifactStamps,secondArtifactStamps) && ...
    isequaln(firstInvocation.ValidationSummary, ...
    secondInvocation.ValidationSummary) && ...
    isequal(firstInvocation.NMAAllocation.TargetWidths, ...
    secondInvocation.NMAAllocation.TargetWidths) && ...
    firstInvocation.Passed && secondInvocation.Passed && ...
    ~firstInvocation.PredictiveMetricsForInference && ...
    ~secondInvocation.PredictiveMetricsForInference && ...
    firstInvocation.OuterTestSealed && ...
    secondInvocation.OuterTestSealed && ...
    ~firstInvocation.OuterTestEvaluated && ...
    ~secondInvocation.OuterTestEvaluated, ...
    "NMA:CVV4SmokeRestartabilityFailure", ...
    "The v4 engineering smoke is not exactly restartable and sealed.");

