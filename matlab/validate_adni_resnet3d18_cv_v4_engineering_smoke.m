function validate_student(artifact,method,numTrain,numValidation)
training = artifact.Training;
actualParameters = sum(cellfun( ...
    @numel,training.Network.Learnables.Value));
analyticalParameters = nma_resnet3d18_resource( ...
    artifact.Allocation.TargetWidths, ...
    Resource="parameters",NumClasses=3);
assert(artifact.Method == method && ...
    ~training.TestEvaluated && ...
    training.Options.MaxEpochs == 1 && ...
    training.Options.InitialLearnRate == 2e-5 && ...
    training.Options.MinimumLearnRateRatio == 0.1 && ...
    training.Options.Alpha == 0.9 && ...
    training.Options.Temperature == 2 && ...
    training.Options.L2Regularization == 1e-4 && ...
    training.Options.GradientThreshold == 5 && ...
    training.Options.ValidationPatience == 1 && ...
    training.Options.TrainingSampling == ...
    "one-visit-per-subject" && ...
    training.Options.RandomSeed == 20260820 && ...
    training.NumTrainSubjects == numTrain && ...
    training.NumValidationSubjects == numValidation && ...
    training.NumOptimizationSamplesPerEpoch == numTrain && ...
    training.BestValidation.Split == "validation" && ...
    training.BestValidation.NumSubjects == numValidation && ...
    all(isfinite(training.History{:,2:6}),"all") && ...
    all(isfinite( ...
    training.OptimizerDiagnostics.TrainableGradientNorm)) && ...
    actualParameters == analyticalParameters && ...
    actualParameters == ...
    artifact.Surgery.CompressedLearnableParameters, ...
    "NMA:InvalidCVV4SmokeStudent", ...
    "The independently loaded %s smoke student is invalid.",method);
end

function maximumError = calibration_maximum_error(first,second)
assert(isequal(first.Probes.Probe,second.Probes.Probe) && ...
    first.NumImages == second.NumImages && ...
    first.NumBatches == second.NumBatches && ...
    isequal(first.ClassWeights,second.ClassWeights), ...
    "NMA:CVV4SmokeCalibrationStructureMismatch", ...
    "The reproduced smoke calibration structure changed.");
errors = [ ...
    max(abs(first.Losses-second.Losses),[],"all"); ...
    max(abs(first.Probes.ForwardMeanSquare- ...
    second.Probes.ForwardMeanSquare),[],"all"); ...
    max(abs(first.Probes.BackwardMeanSquare- ...
    second.Probes.BackwardMeanSquare),[],"all"); ...
    max(abs(first.Probes.MultiplicativeMeanAbs- ...
    second.Probes.MultiplicativeMeanAbs),[],"all")];
maximumError = max(errors);
for probeIndex = 1:height(first.Probes)
    channelErrors = [ ...
        max(abs(first.Probes.ForwardByChannel{probeIndex}- ...
        second.Probes.ForwardByChannel{probeIndex}),[],"all"); ...
        max(abs(first.Probes.BackwardByChannel{probeIndex}- ...
        second.Probes.BackwardByChannel{probeIndex}),[],"all"); ...
        max(abs(first.Probes.MultiplicativeByChannel{probeIndex}- ...
        second.Probes.MultiplicativeByChannel{probeIndex}),[],"all")];
    maximumError = max(maximumError,max(channelErrors));
end
end

function matches = surgery_matches(first,second)
matches = isequal(first.TargetWidths,second.TargetWidths) && ...
    first.CompressedLearnableParameters == ...
    second.CompressedLearnableParameters && ...
    first.CompressedMACs == second.CompressedMACs && ...
    first.CompressedActivationProxy == ...
    second.CompressedActivationProxy && ...
    numel(first.StageMasks) == numel(second.StageMasks);
if ~matches
    return
end
for stage = 1:numel(first.StageMasks)
    if ~isequal(first.StageMasks{stage},second.StageMasks{stage})
        matches = false;
        return
    end
end
firstFields = sort(string(fieldnames(first.HiddenMasks)));
secondFields = sort(string(fieldnames(second.HiddenMasks)));
if ~isequal(firstFields,secondFields)
    matches = false;
    return
end
for fieldIndex = 1:numel(firstFields)
    field = firstFields(fieldIndex);
    if ~isequal(first.HiddenMasks.(field), ...
            second.HiddenMasks.(field))
        matches = false;
        return
    end
end
end

function evaluation = reproduce_validation( ...
    network,manifestFile,storedTraining,storedCell,numSubjects)
assert(storedTraining.Split == "validation" && ...
    storedCell.Split == "validation" && ...
    storedTraining.NumSubjects == numSubjects && ...
    storedCell.NumSubjects == numSubjects, ...
    "NMA:InvalidCVV4SmokeStoredValidation", ...
    "A stored smoke result is not validation-only.");
evaluation = adni_evaluate_resnet3d18( ...
    network,manifestFile,Split="validation", ...
    ExecutionEnvironment="gpu",BootstrapReplicates=0);
assert(predictions_match(evaluation,storedTraining) && ...
    predictions_match(evaluation,storedCell), ...
    "NMA:CVV4SmokePredictionReproductionMismatch", ...
    "A smoke network does not reproduce validation predictions.");
end

function matches = predictions_match(first,second)
firstRows = first.SubjectPredictions;
secondRows = second.SubjectPredictions;
matches = isequal(firstRows.Subject,secondRows.Subject) && ...
    isequal(firstRows.TrueGroup,secondRows.TrueGroup) && ...
    isequal(firstRows.PredictedGroup,secondRows.PredictedGroup) && ...
    max(abs(firstRows{:,{'ScoreAD','ScoreCN','ScoreMCI'}}- ...
    secondRows{:,{'ScoreAD','ScoreCN','ScoreMCI'}}),[],"all") <= 1e-5 && ...
    abs(first.BalancedAccuracy-second.BalancedAccuracy) <= 1e-12 && ...
    abs(first.MacroF1-second.MacroF1) <= 1e-12 && ...
    abs(first.Accuracy-second.Accuracy) <= 1e-12;
end

function stamp = file_stamp(path)
information = dir(path);
assert(isscalar(information), ...
    "NMA:CVV4SmokeValidationStampFailure", ...
    "Could not inspect smoke file %s.",path);
stamp = struct( ...
    "Path",string(path),"Bytes",information.bytes, ...
    "Modified",information.datenum);
end

function stamp = empty_stamp()
stamp = struct("Path","","Bytes",0,"Modified",0);
end

function restore_gpu_state(previousDeterminism,previousGPUGenerator)
deep.gpu.deterministicAlgorithms(previousDeterminism);
gpurng(previousGPUGenerator);
end
